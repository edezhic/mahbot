/// How many reader connections one store keeps.
///
/// Two bounds fix this count. The floor is two: one read that is slow, or whose
/// caller has already given up, must never by itself make the next read wait for
/// a reader. The ceiling would be the engine's reading positions — the one thing
/// in this file that could make a read fail where it used to succeed. The source
/// keeps a handful of frame-valued read marks, four of them for readers, which
/// reads like four positions is all there is (three readers plus the writing
/// connection's own statement); the measurement is what settles it, and it is
/// what this count rests on: `readers_at_distinct_frames_are_all_admitted` holds
/// twenty-four live, only-partly-stepped reads at twenty-four distinct frames at
/// once, and every one of them is admitted — the engine hands a reader the
/// highest read mark at or below its snapshot instead of handing out one
/// position per reader.
///
/// Accepted residual: were the engine ever to deny a reader a position anyway
/// (the retry-then-`Busy` path the source reads like), it would surface as that
/// one read's own engine error after the engine's own retry — never as a state
/// change, and never as a failure of the store.
///
/// The cost is per connection and is accepted: each reader carries its own page
/// cache (2000 pages, ~8 MiB), its own prepared-statement cache (filled from the
/// same SQL the writing connection prepares, so a statement is prepared once per
/// reader) and its own connect — the engine's connect is blocking, so the first
/// read that needs a reader pays for the readers it creates. That steady-state
/// memory is the price of reads that do not wait.
const READER_CONNECTIONS: usize = 3;

/// How long a connection waits on a lock another process holds, before giving up
/// with a busy error — the writing connection ([`Connection::open`]) and every
/// reader ([`ReaderPool::create_readers`]) alike: every connection carries the
/// per-connection settings it needs.
const BUSY_TIMEOUT: Duration = Duration::from_mins(1);

/// How long [`ReaderPool::quiet`] and [`ReaderPool::release`] wait for the
/// readers to fall idle before giving up on waiting.
///
/// A reader serves one read at a time, so the readers fall idle in the time a
/// read takes; the wait only runs long when a read was abandoned by a caller
/// that gave up. Giving up on the wait is what keeps a store repair, and the
/// exit round's checkpoint, from hanging behind such a read.
const READERS_IDLE_WAIT: Duration = Duration::from_secs(5);

/// Why a read issued by the task that holds a transaction is refused.
const TRANSACTION_READ_REFUSAL: &str = "a read issued while this task holds an open \
     transaction on the connection must be served by the transaction itself \
     (TxGuard::query): a reader connection cannot see what the transaction has \
     written";

/// PRAGMA names a **read-only** connection may run: the read-shaped pragmas of
/// the inspection path, shared by the reader guard ([`reader_refusal`]) and the
/// debug validator ([`crate::db::debug::validate_read_only`]) so the two cannot
/// drift.
///
/// A mutating PRAGMA is not on the list. A bracketed or quoted name is the name
/// inside it ([`pragma_form`]), which is also how the validator's tokenizer
/// hands a name over — so the two agree on which name a statement runs. On the
/// inspection path this allowlist is defense-in-depth on top of the engine's own
/// read-only switch; on a reader connection it is what covers the pragmas that
/// switch leaves unclassified (`PRAGMA wal_checkpoint` compacts the store file
/// and `PRAGMA journal_mode` rewrites its header, and neither is refused by
/// it).
///
/// `foreign_key_check` is on the list because this product issues it as a read
/// ([`crate::db::migrations`], after a consolidation import) — the engine does
/// not know the name and answers it with no rows, so it changes nothing either
/// way. The engine's own foreign-key read is `foreign_key_list`, which is listed
/// beside it.
pub(crate) const READER_PRAGMAS: &[&str] = &[
    "quick_check",
    "integrity_check",
    "table_info",
    "table_xinfo",
    "index_info",
    "index_list",
    "index_xinfo",
    "foreign_key_check",
    "foreign_key_list",
    "database_list",
    "compile_options",
    "page_count",
    "freelist_count",
    "page_size",
    "encoding",
    "user_version",
    "schema_version",
    "collation_list",
    "function_list",
    "module_list",
    "pragma_list",
    "table_list",
    "stats",
];

/// The listed pragmas whose body is a **query** whatever it looks like: the ten
/// names the engine routes to its query path for both the call form and the `=`
/// form (its `translate/pragma.rs` match on the name behind `Equals | Call`).
/// That is why `PRAGMA table_info = tickets` reads rather than assigns, and why
/// [`reader_refusal`] lets their assignment form through; every other listed name
/// is taken with a value only as a setter, and a reader refuses that.
const QUERY_BODY_PRAGMAS: &[&str] = &[
    "quick_check",
    "integrity_check",
    "table_info",
    "table_xinfo",
    "index_info",
    "index_xinfo",
    "index_list",
    "foreign_key_list",
    "database_list",
    "table_list",
];

/// The statement forms a reader connection refuses, as the reason to show, or
/// `None` when the statement may run.
///
/// A reader connection is read-only for its whole life: it is created with
/// `PRAGMA query_only = 1` and the switch is never turned off, so the engine
/// itself refuses every change it classifies as a write when a statement is
/// prepared — DML, DDL, `VACUUM`, `REINDEX` and the pragma setters it
/// classifies as writes. What the switch does **not** refuse is what this guard
/// covers: transaction control (`BEGIN`/`COMMIT`/`ROLLBACK`/`SAVEPOINT`/
/// `RELEASE`), `ATTACH`/`DETACH`, and the pragmas that write without being
/// classified as writes (`PRAGMA wal_checkpoint`, `PRAGMA journal_mode`).
///
/// It is an allowlist ([`READER_PRAGMAS`]) plus a bounded prefix look at the
/// statement's leading form and at whether a pragma's body assigns to it
/// ([`QUERY_BODY_PRAGMAS`]) — not a classification pass over the SQL — so it also
/// refuses reads it does not need to refuse: a pragma absent from the list, and
/// any assignment to a name whose body the engine does not route as a query.
/// Refusing a read costs a caller an error message, never a guarantee, so the
/// list errs that way on purpose.
///
/// One verdict per statement, whichever connection serves it: the reader entry
/// applies this on a reader ([`ReaderLease::run`]), and the read-only inspection
/// path applies it on the writing-connection fallback
/// ([`Connection::query_readonly`]) — a raw client cannot do on the fallback what
/// a reader turns away. The narrowing that follows for such a client (a no-op
/// setter like `PRAGMA page_size = 8192` is refused where the fallback used to
/// accept it) is intended.
///
/// The call form of a listed name (`PRAGMA page_size(8192)`) is left to the
/// engine: of the listed names only `page_size`, `user_version` and
/// `schema_version` are settable, and against an initialized store the first is
/// a no-op, the third an explicit no-op, and the second a write the read-only
/// switch itself refuses — so a reader cannot change state through one.
///
/// The failure it prevents is a change that succeeds on a reader and is never
/// recorded: change capture runs on the writing connection only, so a change
/// committed anywhere else never reaches the store's own record of changes —
/// which is what the ticket chronicle (`ticket_chronicle`) is materialized
/// from.
pub(crate) fn reader_refusal(sql: &str) -> Option<String> {
    let (keyword, rest) = leading_form(sql);
    let upper = keyword.to_ascii_uppercase();
    if matches!(
        upper.as_str(),
        "BEGIN" | "COMMIT" | "END" | "ROLLBACK" | "SAVEPOINT" | "RELEASE" | "ATTACH" | "DETACH"
    ) {
        return Some(format!(
            "refused on a read-only connection: '{upper}' can change state, and the store's \
             readers never change state"
        ));
    }
    if upper == "PRAGMA" {
        let (name, args) = pragma_form(rest);
        let lower = name.to_ascii_lowercase();
        if !READER_PRAGMAS.contains(&lower.as_str()) {
            // A name that resolved to nothing (`PRAGMA [wal_checkpoint`, an
            // unterminated bracket) is not one this guard can clear: name what
            // was actually written instead of an empty pragma.
            let shown = if name.is_empty() {
                rest.trim().trim_end_matches(';').trim_end()
            } else {
                name
            };
            return Some(format!(
                "refused on a read-only connection: PRAGMA '{shown}' is not one of the pragmas \
                 a reader may run"
            ));
        }
        // An assignment is the `=` as the first thing after the name: an
        // argument (`PRAGMA table_info('a=b')`) is not one, whatever it holds.
        if skip_leading(args).starts_with('=') && !QUERY_BODY_PRAGMAS.contains(&lower.as_str()) {
            return Some(format!(
                "refused on a read-only connection: PRAGMA '{name}' may be read, never assigned — \
                 a reader's own state never changes"
            ));
        }
    }
    None
}

/// The name a `PRAGMA …` statement runs and the text after it: a quoted or
/// bracketed name (`[table_info]`, `"table_info"`, `` `table_info` ``) is the
/// name inside, which is how the engine reads it and how the debug validator's
/// tokenizer hands it over — so a bracketed pragma the inspection path accepts
/// is not refused here for being bracketed.
///
/// An unterminated quoting (`PRAGMA [wal_checkpoint`) resolves to no name at
/// all, and the allowlist then refuses the statement — as does the engine,
/// which cannot parse it either.
fn pragma_form(rest: &str) -> (&str, &str) {
    let rest = skip_leading(rest);
    let Some(open) = rest.chars().next().filter(|c| matches!(c, '[' | '"' | '`')) else {
        return leading_form(rest);
    };
    let close = if open == '[' { ']' } else { open };
    match rest[open.len_utf8()..].split_once(close) {
        Some((name, tail)) => (name, tail),
        None => ("", rest),
    }
}

/// Split a statement's leading form: the leading word and the rest after it,
/// with leading whitespace, statement separators and `--` / `/* */` comments
/// skipped.
fn leading_form(sql: &str) -> (&str, &str) {
    let rest = skip_leading(sql);
    match rest.find(|c: char| !c.is_ascii_alphanumeric() && c != '_') {
        Some(end) => (&rest[..end], &rest[end..]),
        None => (rest, ""),
    }
}

/// Skip what the engine's parser skips before a statement: whitespace,
/// statement separators and `--` / `/* */` comments.
///
/// The separators matter: the engine runs the statement after a leading `;` (an
/// empty statement is nothing), so a guard that stopped at one would be
/// bypassed by a single character.
fn skip_leading(sql: &str) -> &str {
    let mut rest = sql;
    loop {
        rest = rest.trim_start_matches(|c: char| c.is_whitespace() || c == ';');
        if let Some(after) = rest.strip_prefix("--") {
            rest = after.split_once('\n').map_or("", |(_, tail)| tail);
        } else if let Some(after) = rest.strip_prefix("/*") {
            rest = after.split_once("*/").map_or("", |(_, tail)| tail);
        } else {
            return rest;
        }
    }
}

/// A store's reader connections: a small fixed set of read-only connections to
/// the same open store, each serving one read at a time.
///
/// # What they are for
///
/// A read used to be issued on the writing connection and therefore queue behind
/// whatever else the store was doing — a read issued while the periodic
/// integrity verification was under way waited seconds, against an ordinary read
/// cost of milliseconds. A read of its own is served at once instead, and reads
/// do not queue behind one another while a reader is free.
///
/// # Discipline
///
/// * Every connection here comes from the already-open store
///   ([`store::Database::connect`]): a store file is never opened a second time,
///   because the engine holds a whole-file lock on it for the process's life and
///   closing any descriptor for that file drops every record lock the process
///   holds on it (see [`crate::db::wal_guard`]). The pool holds the store handle,
///   so the handle outlives the connections made from it.
/// * Readers are created on the first read that needs one, and only after
///   [`Connection::enable_readers`] — so opening a store, including the many
///   stores the checks open, pays nothing for readers it never uses.
/// * Each reader is read-only for its whole life (see [`reader_refusal`]), and
///   change capture is never enabled on one: the engine records a change on the
///   connection that commits it, so the record is complete exactly because no
///   change may be committed anywhere but the writing connection. A reader can
///   also never be left with a transaction open — transaction control is one of
///   the forms the guard refuses — so there is nothing to roll back on one.
///
/// # What is accepted
///
/// * A read waits for a reader only while every reader is busy; one read whose
///   caller has already given up can hold one reader, never the pool.
/// * A read no longer queues behind another task's open state change, so it may
///   see the state as of just before that change is committed — never older than
///   that.
/// * A reader's cache is its own and the engine clears it at the start of a
///   read once it sees the journal has moved — no writer-side code drops another
///   connection's cache — so a read that follows a commit re-reads what it
///   needs: a read can be slower than it would have been on the writing
///   connection while the store is being written to.
/// * A reading position can be refused to a reader in the engine's own terms
///   (see the count's doc): the read then fails with the engine's own error
///   after the engine's own retry, and never as a state change.
/// * The pool's steady-state memory (three connections' own caches) and the
///   one-time cost of creating them, paid by the first read that needs one.
struct ReaderPool {
    /// The open store the readers are made from.
    db: Arc<store::Database>,
    /// The free readers, and whether they have been created yet.
    inner: tokio::sync::Mutex<ReaderPoolInner>,
    /// Woken when a reader is given back to `inner.idle`.
    freed: tokio::sync::Notify,
    /// Whether the readers are in service. Reads are served by the writing
    /// connection while it is `false`: before [`Connection::enable_readers`],
    /// while a repair holds the store quiet, and once the store is on its way
    /// down.
    in_service: tokio::sync::watch::Sender<bool>,
    /// Set by [`ReaderPool::release`], never cleared: the store is on its way
    /// down and the readers are gone for good. It is what keeps a repair's
    /// [`QuietReaders`] guard, dropped after the release, from putting readers
    /// back in service during the exit sequence.
    released: AtomicBool,
}

/// [`ReaderPool`]'s state under its lock.
struct ReaderPoolInner {
    /// The free readers — empty until the first read creates them, and while
    /// every reader is serving a read.
    idle: Vec<store::Connection>,
    /// How far the pool has got with creating them.
    state: Readers,
}

/// How far a pool has got with creating its readers.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Readers {
    /// Not created yet: the first read that needs one creates them.
    Uncreated,
    /// Created — in `idle`, or serving a read.
    Created,
    /// Creation failed, and is not retried: every read from then on is served by
    /// the writing connection, which is where reads were served before readers
    /// existed. The reason was logged where the creation failed.
    Failed,
}

impl std::fmt::Debug for ReaderPool {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ReaderPool")
            .field("connections", &READER_CONNECTIONS)
            .finish()
    }
}

impl ReaderPool {
    fn new(db: Arc<store::Database>) -> Self {
        Self {
            db,
            inner: tokio::sync::Mutex::new(ReaderPoolInner {
                idle: Vec::new(),
                state: Readers::Uncreated,
            }),
            freed: tokio::sync::Notify::new(),
            in_service: tokio::sync::watch::channel(false).0,
            released: AtomicBool::new(false),
        }
    }

    /// Put the readers in service — see [`Connection::enable_readers`].
    ///
    /// `send_replace` rather than `send`: the pool holds no receiver of its own,
    /// and a `watch` sender refuses to send while no receiver exists.
    fn enable(&self) {
        self.in_service.send_replace(true);
    }

    /// Hand out a reader for one read, creating the readers on first use, or
    /// `None` when no reader can serve this read (not in service, creation
    /// failed, or they went out of service while this call waited for a free
    /// one). The caller then serves the read on the writing connection.
    async fn lease(self: &Arc<Self>) -> Option<ReaderLease> {
        let mut in_service = self.in_service.subscribe();
        loop {
            if !*in_service.borrow() {
                return None;
            }
            {
                let mut inner = self.inner.lock().await;
                // Re-checked while holding the lock: the check above is already
                // stale by the time this call gets the lock, and a read that got
                // past it after a quiet() had drained the pool would create
                // readers and run on one — exactly what the quiet() was for.
                if !*in_service.borrow() {
                    return None;
                }
                match inner.state {
                    Readers::Created => {}
                    // Not retried: a creation that failed stays failed, and the
                    // reads it could not serve keep being served the way they
                    // were before the pool existed.
                    Readers::Failed => return None,
                    Readers::Uncreated => match self.create_readers().await {
                        Ok(made) => {
                            debug!(
                                connections = made.len(),
                                "reader connections created — this store's reads are served by \
                                 them from now on"
                            );
                            inner.idle = made;
                            inner.state = Readers::Created;
                        }
                        Err(reason) => {
                            error!(
                                reason,
                                "could not create the store's reader connections — reads stay \
                                 on the writing connection"
                            );
                            inner.state = Readers::Failed;
                            return None;
                        }
                    },
                }
                if let Some(conn) = inner.idle.pop() {
                    return Some(ReaderLease {
                        pool: Arc::clone(self),
                        conn,
                    });
                }
            }
            tokio::select! {
                () = self.freed.notified() => {}
                changed = in_service.changed() => {
                    if changed.is_err() || !*in_service.borrow() {
                        return None;
                    }
                }
            }
        }
    }

    /// Take the readers out of service and wait for them to fall idle, closing
    /// them so nothing they hold predates the work the caller is about to do.
    /// `None` when they did not fall idle within [`READERS_IDLE_WAIT`]: the
    /// caller then defers rather than running against live readers.
    async fn quiet(self: &Arc<Self>) -> Option<QuietReaders> {
        if !*self.in_service.borrow() || self.released.load(Ordering::SeqCst) {
            return Some(QuietReaders { pool: None });
        }
        self.in_service.send_replace(false);
        if self.drain_idle().await {
            Some(QuietReaders {
                pool: Some(Arc::clone(self)),
            })
        } else {
            // Back in service — unless the store was released while this call
            // waited: the release is final.
            if !self.released.load(Ordering::SeqCst) {
                self.in_service.send_replace(true);
            }
            None
        }
    }

    /// Take the readers out of service for good — see
    /// [`Connection::release_readers`].
    async fn release(self: &Arc<Self>) {
        self.released.store(true, Ordering::SeqCst);
        self.in_service.send_replace(false);
        let _ = self.drain_idle().await;
    }

    /// Close the readers once every one of them is idle. `false` when they did
    /// not all fall idle within [`READERS_IDLE_WAIT`]. A reader still out at
    /// that point keeps its own connection (and its reading position) until the
    /// runtime drops it.
    async fn drain_idle(&self) -> bool {
        let deadline = tokio::time::Instant::now() + READERS_IDLE_WAIT;
        loop {
            {
                let mut inner = self.inner.lock().await;
                let all_idle = match inner.state {
                    // Nothing was created, so nothing is out.
                    Readers::Uncreated | Readers::Failed => true,
                    Readers::Created => inner.idle.len() == READER_CONNECTIONS,
                };
                if all_idle {
                    // A pool that had readers is back to not having any: the
                    // next read that needs one creates them again. A failed
                    // creation is not one of those — it stays failed.
                    inner.idle.clear();
                    if inner.state == Readers::Created {
                        inner.state = Readers::Uncreated;
                    }
                    return true;
                }
            }
            if tokio::time::timeout_at(deadline, self.freed.notified())
                .await
                .is_err()
            {
                return false;
            }
        }
    }

    /// Return a reader after a read. A reader given back after the pool was
    /// drained is closed instead of kept: the drain is what emptied it.
    async fn give_back(&self, conn: store::Connection) {
        {
            let mut inner = self.inner.lock().await;
            if inner.state == Readers::Created {
                inner.idle.push(conn);
            }
        }
        self.freed.notify_one();
    }

    /// Create the readers. Every reader carries the per-connection settings the
    /// writing connection gets, plus the read-only switch, which is set here —
    /// before any statement is prepared on the connection — and never reset.
    ///
    /// The engine's connect is blocking (it reads the store header and page 1
    /// and refreshes its stats snapshot), so it runs off the async worker pool.
    async fn create_readers(&self) -> Result<Vec<store::Connection>, String> {
        let mut made = Vec::with_capacity(READER_CONNECTIONS);
        for _ in 0..READER_CONNECTIONS {
            let conn = crate::util::with_block_in_place(|| self.db.connect())
                .map_err(|e| format!("could not connect a reader: {e}"))?;
            conn.busy_timeout(BUSY_TIMEOUT);
            conn.execute("PRAGMA temp_store = MEMORY;", ())
                .await
                .map_err(|e| format!("could not set a reader's in-memory temp storage: {e}"))?;
            conn.execute("PRAGMA query_only = 1;", ())
                .await
                .map_err(|e| format!("could not make a reader read-only: {e}"))?;
            made.push(conn);
        }
        Ok(made)
    }
}

/// Held for the duration of a repair that must not run while the readers are in
/// use: the readers are out of service (reads are served by the writing
/// connection) and closed. Dropping the guard puts them back in service — unless
/// the store has already released them for good ([`ReaderPool::release`], the
/// exit path), which a guard dropped late must not undo — and the next read
/// creates them again.
struct QuietReaders {
    pool: Option<Arc<ReaderPool>>,
}

impl Drop for QuietReaders {
    fn drop(&mut self) {
        if let Some(pool) = &self.pool
            && !pool.released.load(Ordering::SeqCst)
        {
            pool.in_service.send_replace(true);
        }
    }
}

/// One read's hold on one reader connection.
struct ReaderLease {
    pool: Arc<ReaderPool>,
    conn: store::Connection,
}

impl ReaderLease {
    /// Run one read on this reader.
    ///
    /// The read runs in a DETACHED task, so a caller that gave up (a timeout, a
    /// shutdown cut, an aborted task) ends only its own wait: the statement
    /// finishes on the reader and the reader returns to the pool when it does.
    /// The statement itself is bounded too — every connection this product
    /// opens carries the per-statement limit
    /// ([`crate::db::store::statement_limit`]), which the engine arms on the
    /// connection and enforces as it steps, so a statement that overruns it is
    /// terminated and the reader stays usable. Nothing here has to stop a
    /// statement in place; abandoning the caller's wait never needs to.
    ///
    /// The statement is checked against [`reader_refusal`] first, so a change
    /// routed here fails loudly instead of committing without ever being
    /// recorded.
    async fn run<T, F>(self, sql: &str, op: F) -> turso::Result<T>
    where
        T: Send + 'static,
        F: for<'a> FnOnce(
                &'a store::Connection,
            ) -> std::pin::Pin<
                Box<dyn std::future::Future<Output = turso::Result<T>> + Send + 'a>,
            > + Send
            + 'static,
    {
        let Self { pool, conn } = self;
        let sql = sql.to_owned();
        let task = async move {
            let outcome = AssertUnwindSafe(async {
                if let Some(refusal) = reader_refusal(&sql) {
                    return Err(turso::Error::Error(refusal));
                }
                op(&conn).await
            })
            .catch_unwind()
            .await;
            // The reader goes back before a panic is re-raised: the engine's own
            // statement cleanup has run by then, and a reader holds no
            // transaction (the guard above is what keeps one from being opened).
            pool.give_back(conn).await;
            match outcome {
                Ok(inner) => inner,
                Err(payload) => std::panic::resume_unwind(payload),
            }
        };
        join_detached(tokio::spawn(task).await)
    }
}

/// Collect problem rows from `PRAGMA quick_check` (skipping `"ok"` and the
/// known FTS index-cardinality false positive). Used by
/// [`Connection::quick_check_problems`].
fn scan_integrity_rows(rows: &[Row]) -> anyhow::Result<Vec<String>> {
    let mut problems: Vec<String> = Vec::new();
    for row in rows {
        match row.get_value(0)? {
            Value::Text(s) if s == "ok" => {}
            Value::Text(s) if s.contains(KNOWN_FTS_DIR_COUNT_FALSE_POSITIVE) => {}
            Value::Text(s) => problems.push(s),
            _ => anyhow::bail!("Unexpected result from PRAGMA quick_check"),
        }
    }
    Ok(problems)
}

/// Outcome of `PRAGMA wal_checkpoint`, parsed from its 3-column result row
/// (`busy`, `log`, `checkpointed`).
///
/// The engine's success path writes `busy == 0`; a checkpoint it could not run
/// (blocked or genuinely failed) leaves the row with `busy` set and the frame
/// columns NULL, and that row is refused by [`parse_checkpoint_row`] — so a
/// completed or partial checkpoint is the only thing parsed into this type, and
/// a partial one is detected via `log > checkpointed` (frames remaining in the
/// WAL).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct CheckpointOutcome {
    /// True when the engine's row itself says the attempt was blocked. The
    /// shipped engine never writes that row with frame counts (its blocked row
    /// carries none, and the parse refuses it), so this is false for every row
    /// that reaches here — it stays a field of the outcome so the arms that
    /// render a partial attempt keep rendering it.
    pub busy: bool,
    /// WAL frame high-water mark after the checkpoint (`-1` for non-WAL
    /// databases). After a complete TRUNCATE the frame index resets, so this
    /// equals `checkpointed_frames`; `is_complete` relies on that reset.
    pub log_frames: i64,
    /// Frames backfilled into the database by the checkpoint (`-1` for
    /// non-WAL databases).
    pub checkpointed_frames: i64,
}

impl CheckpointOutcome {
    /// True when every WAL frame was backfilled and no busy condition was hit.
    #[must_use]
    pub fn is_complete(&self) -> bool {
        !self.busy && self.log_frames <= self.checkpointed_frames
    }
}

/// Read an integer column from a checkpoint result row.
fn int_column(row: &Row, idx: usize) -> anyhow::Result<i64> {
    match row.get_value(idx)? {
        Value::Integer(n) => Ok(n),
        _ => anyhow::bail!("Unexpected result from PRAGMA wal_checkpoint"),
    }
}

/// `PRAGMA wal_checkpoint`'s three columns as a [`CheckpointOutcome`].
///
/// The engine answers a checkpoint it could not run — blocked by another
/// connection's reading position, or genuinely failed in its pager — with a
/// *successful* statement whose row is `busy` set and the two frame columns NULL:
/// it fills those on the success path only, and emits its own reason as a
/// debug-level event rather than as an SQL error ([`checkpoint_cause`] captures
/// that event when the caller armed a sink). The two answers are therefore
/// indistinguishable from the row, and the NULL frame columns are what says so:
/// the row is refused here, and the captured reason is what tells a blocked
/// attempt from a genuine failure from then on (see
/// [`crate::db::checkpoint_cause::is_blocked_checkpoint`]).
fn parse_checkpoint_row(row: &Row) -> anyhow::Result<CheckpointOutcome> {
    Ok(CheckpointOutcome {
        busy: int_column(row, 0)? != 0,
        log_frames: int_column(row, 1)?,
        checkpointed_frames: int_column(row, 2)?,
    })
}

/// A locked handle on the writing connection, scoped to a single transaction.
/// Holds the mutex guard for the entire duration — a dropped guard triggers a
/// rollback on the next write.
///
/// The transaction's own work goes through this guard: `query` for what it
/// reads, `execute` / `upsert_row` / `execute_batch` for what it changes, and
/// `execute_one` for a change that reads its own result back.
///
/// It is the only place a read can see the
/// transaction's own uncommitted writes, and the connection's read entry refuses
/// a read issued by the task holding the guard (see
/// [`Connection::refuse_transaction_read`]) precisely so that a read cannot
/// drift onto a reader behind the transaction's back.
pub(crate) struct TxGuard<'a> {
    conn: tokio::sync::MutexGuard<'a, store::Connection>,
    /// Shared flag on the parent Connection; set in Drop to signal a deferred
    /// rollback on the next write operation. Set to None when the transaction
    /// has been explicitly committed or rolled back, preventing Drop from
    /// flagging a dangling transaction.
    has_dangling_tx: Option<Arc<AtomicBool>>,
    /// The parent's owning-task record, cleared with the flag above so the
    /// connection's read entry stops refusing that task's reads.
    tx_task: Option<Arc<std::sync::Mutex<Option<tokio::task::Id>>>>,
}

impl TxGuard<'_> {
    /// Upsert one row without the engine's `INSERT ... ON CONFLICT ... DO UPDATE`
    /// form: `update_sql` runs first, and when it matched no row `insert_sql`
    /// creates one.
    ///
    /// `insert_sql` must be an `INSERT ... ON CONFLICT ... DO NOTHING`, so a row
    /// created by another writer in between is not an error; that insert then
    /// reports zero rows and the update runs once more, so the caller's values
    /// win. `update_params` is a closure because the update can run twice.
    /// Callers that need the pair to be atomic run it inside a transaction (both
    /// `session_metadata` paths do).
    ///
    /// The engine's upsert form is unusable while change capture is enabled on
    /// the store (`PRAGMA capture_data_changes_conn`); only its `DO UPDATE`
    /// branch has been observed to abort, with a record-decode error (`Payload
    /// too small for indicated header size`, `Invalid Text value`, `TEXT value
    /// contains invalid UTF-8`). The precise engine condition is not isolated.
    ///
    /// A caller that wraps this write's error in its own context must render the
    /// whole `anyhow` chain when it reports the failure (`?e`, or `{:#}` in a
    /// message): the outer context alone (`%e`) hides the engine's cause.
    pub async fn upsert_row<U, I>(
        &self,
        update_sql: &str,
        update_params: impl Fn() -> U,
        insert_sql: &str,
        insert_params: I,
    ) -> turso::Result<()>
    where
        U: IntoParams + Send + 'static,
        I: IntoParams + Send + 'static,
    {
        if self.execute(update_sql, update_params()).await? > 0 {
            return Ok(());
        }
        if self.execute(insert_sql, insert_params).await? == 0 {
            self.execute(update_sql, update_params()).await?;
        }
        Ok(())
    }

    pub async fn execute(
        &self,
        sql: &str,
        params: impl IntoParams + Send + 'static,
    ) -> turso::Result<u64> {
        self.conn.execute(sql, params).await
    }

    /// Execute multiple SQL statements (e.g. a schema) inside the transaction.
    pub async fn execute_batch(&self, sql: &str) -> turso::Result<()> {
        self.conn.execute_batch(sql).await
    }

    /// Execute a read of the transaction's own work, returning zero or more
    /// rows. Returns an empty Vec when no rows match.
    ///
    /// This is the only read that sees what the transaction itself has written,
    /// and the connection's read entry refuses a read issued by this task while
    /// the transaction is open (see
    /// [`Connection::refuse_transaction_read`]) — so the transaction's own work
    /// reads here.
    pub async fn query(
        &self,
        sql: &str,
        params: impl IntoParams + Send + 'static,
    ) -> turso::Result<Vec<Row>> {
        Connection::query_impl(&self.conn, sql, params).await
    }

    /// Execute a **change** of the transaction's own work that returns exactly
    /// one row.
    pub async fn execute_one<T, E>(
        &self,
        sql: &str,
        params: impl IntoParams + Send + 'static,
        map: impl FnOnce(&Row) -> std::result::Result<T, E> + Send + 'static,
    ) -> turso::Result<T>
    where
        T: Send + 'static,
        E: std::fmt::Display + Send + Sync + 'static,
    {
        Connection::query_row_impl(&self.conn, sql, params, map).await
    }

    /// Execute a read of the transaction's own work, mapping each row, failing on
    /// the first per-row error.
    pub async fn query_map_strict<T, E>(
        &self,
        sql: &str,
        params: impl IntoParams + Send + 'static,
        map: impl FnMut(&Row) -> std::result::Result<T, E> + Send + 'static,
    ) -> anyhow::Result<Vec<T>>
    where
        T: Send + 'static,
        E: std::fmt::Display + Send + Sync + 'static,
    {
        let rows = self.query(sql, params).await?;
        strict_collect(map_rows(&rows, map))
    }

    /// Commit the transaction and release the lock.
    pub async fn commit(mut self) -> turso::Result<()> {
        self.conn.execute("COMMIT", ()).await?;
        // Clear the flags so Drop doesn't try to roll back an already-committed
        // tx, and the read entry stops refusing this task's reads.
        self.has_dangling_tx = None;
        self.release_task_record();
        Ok(())
    }

    /// Rollback the transaction and release the lock.
    pub async fn rollback(mut self) -> turso::Result<()> {
        self.conn.execute("ROLLBACK", ()).await?;
        // Clear the flags so Drop doesn't try to roll back again
        self.has_dangling_tx = None;
        self.release_task_record();
        Ok(())
    }

    /// End this guard's hold on the connection's transaction record: from here on
    /// the task's reads are ordinary reads again. Guard-side only — the parent's
    /// flag itself is left to the write path (see [`Connection::lock_and_cleanup`]).
    fn release_task_record(&mut self) {
        if let Some(task) = self.tx_task.take() {
            *task.lock().unwrap_poison() = None;
        }
    }
}

impl Drop for TxGuard<'_> {
    fn drop(&mut self) {
        // Set the dangling_tx flag on the parent Connection so the next
        // write operation (execute, begin_tx) will issue a ROLLBACK first.
        // This is a deferred pattern — we can't call async methods from Drop,
        // but the lock isn't released yet (MutexGuard is still alive), so
        // no other task can execute a write before the flag is set.
        if let Some(flag) = &self.has_dangling_tx {
            flag.store(true, Ordering::SeqCst);
        }
        // The hold ends with the guard, even when the transaction itself is left
        // for the deferred rollback: a task that dropped its guard no longer has
        // a transaction's own work to read.
        self.release_task_record();
    }
}

// Schema / index management

/// Ensure a full-text search index exists with the correct tokenizer.
/// Drops and recreates if the existing index has a different tokenizer.
///
/// Index maintenance, so its shape probe reads through [`Upkeep`] like the rest
/// of the repair family.
pub(crate) async fn ensure_fts_index(
    conn: &Connection,
    index_name: &str,
    tokenizer: &str,
    ddl: &str,
) -> anyhow::Result<()> {
    let existing_sql: Option<String> = conn
        .upkeep()
        .query_optional(
            "SELECT sql FROM sqlite_master WHERE type='index' AND name=?1 LIMIT 1",
            params![index_name],
            |row| match row.get_value(0)? {
                Value::Text(s) => Ok::<_, ::turso::Error>(s),
                _ => Ok::<_, ::turso::Error>(String::new()),
            },
        )
        .await?
        .filter(|s| !s.is_empty());

    let needs_rebuild = existing_sql
        .as_deref()
        .is_none_or(|sql| !sql.to_lowercase().contains(&tokenizer.to_lowercase()));

    if needs_rebuild {
        // The tokenizer migration drops and recreates the index, so it holds the
        // store's readers off exactly as the corruption rebuilds do — see
        // [`Connection::quiet_readers`] for the premise. At open time this costs
        // nothing: the readers are created by the first read, and this hook runs
        // before any read is served — but the guard is what the code rests on,
        // not that ordering. A read in flight makes the migration wait for the
        // readers to fall idle, and a reader that does not fall idle in time
        // leaves the index as it is: the store still opens, and the next open
        // retries the migration.
        let Some(_quiet) = conn.quiet_readers().await else {
            warn!(
                index = index_name,
                "the store's readers did not fall idle — leaving the FTS index unchanged for \
                 this open; the next open retries the tokenizer migration"
            );
            return Ok(());
        };
        conn.execute(&format!("DROP INDEX IF EXISTS {index_name}"), ())
            .await?;
        // Race-safe: `CREATE INDEX IF NOT EXISTS` prevents failure when two
        // connections run schema init concurrently (e.g. parallel tests).
        conn.execute(ddl, ()).await?;
    }

    Ok(())
}

/// Probe term for the MATCH smoke probe — a plain alphanumeric token, valid
/// for any ngram width; returns zero rows on an empty index but still proves
/// the FTS index is queryable end-to-end.
const FTS_PROBE_TERM: &str = "mahbot";

/// True when a `quick_check` problem is attributable to the ticket-title FTS
/// index: it either names the user-visible index or the internal FTS backing
/// dir (the benign exact count-mismatch message is already filtered by
/// `scan_integrity_rows`; any other internal-dir row is real corruption).
/// core.db carries exactly one FTS index, so internal-dir rows cannot belong
/// to anything else.
fn names_ticket_title_fts(problem: &str, index: &str) -> bool {
    problem.contains(index) || problem.contains(FTS_INTERNAL_INDEX_PREFIX)
}

/// True when the named index is a turso `USING fts` index (its sqlite_master
/// DDL carries the index-method clause). Part of the index repair, so it reads
/// through [`Upkeep`] like the repair's other probes.
async fn is_fts_index(conn: &Connection, index: &str) -> bool {
    conn.upkeep()
        .query_optional(
            "SELECT sql FROM sqlite_master WHERE type = 'index' AND name = ?",
            (index.to_string(),),
            |row| row.get::<String>(0),
        )
        .await
        .ok()
        .flatten()
        .is_some_and(|sql| sql.to_lowercase().contains("using fts"))
}

/// Name of the ticket-title FTS index. This const pair is the single shared
/// known-good copy used by [`crate::db::ensure_fts_index`], the boot repair
/// ([`crate::db::repair_ticket_title_fts_if_corrupt`]), and the runtime repair
/// ([`crate::db::repair_ticket_title_fts_runtime`]) — imported by
/// `crate::pipeline::board::after_open`. The append-only migrations catalog
/// independently carries its own raw-SQL schema entry (by design); the const
/// pair is the authoritative known-good form.
pub(crate) const TICKETS_FTS_INDEX_NAME: &str = "idx_tickets_title_fts";

/// Known-good DDL for the ticket-title FTS index. The const pair is the single
/// shared known-good copy used by [`crate::db::ensure_fts_index`] and the
/// boot/runtime repairs — never rebuilt from `sqlite_master`, whose stored DDL
/// for a corrupt index is untrusted. It is imported by
/// `crate::pipeline::board::after_open`. The append-only migrations catalog
/// carries its own raw-SQL schema entry (by design).
pub(crate) const TICKETS_FTS_INDEX_DDL: &str = "CREATE INDEX IF NOT EXISTS idx_tickets_title_fts ON tickets \
USING fts (title) WITH (tokenizer = 'ngram')";

/// Functional MATCH probe for the ticket-title FTS index: any successful
/// MATCH query proves the index is readable (the incident's corruption also
/// failed plain MATCH queries while quick_check looked clean apart from
/// masked rows). An Err is a detection signal, not a row-count assertion.
/// Upkeep: part of the index repair, so it reads through [`Upkeep`].
async fn title_fts_match_probe(conn: &Connection) -> anyhow::Result<()> {
    conn.upkeep()
        .query_optional(
            "SELECT id FROM tickets WHERE title MATCH ?1 LIMIT 1",
            params![FTS_PROBE_TERM.to_string()],
            |_| Ok::<_, ::turso::Error>(()),
        )
        .await
        .map(|_: Option<()>| ())
}

/// Boot-time corruption probe for the ticket-title FTS index. Returns
/// `Some(evidence)` when the corruption signature is detected (quick_check
/// problems attributable to the index, or a failing MATCH probe), `None`
/// when healthy.
async fn detect_ticket_title_fts_corruption(
    conn: &Connection,
    index: &str,
) -> anyhow::Result<Option<String>> {
    let problems = conn.quick_check_problems().await?;
    let fts_problems: Vec<&str> = problems
        .iter()
        .map(String::as_str)
        .filter(|p| names_ticket_title_fts(p, index))
        .collect();
    if !fts_problems.is_empty() {
        return Ok(Some(fts_problems.join("; ")));
    }
    if let Err(e) = title_fts_match_probe(conn).await {
        return Ok(Some(format!("MATCH probe failed: {e}")));
    }
    Ok(None)
}

/// Post-rebuild verification: filtered quick_check result, index presence in
/// sqlite_master, and a MATCH smoke assertion against a token drawn from a
/// sampled ticket title.
async fn verify_rebuilt_ticket_title_fts(conn: &Connection, index: &str) -> anyhow::Result<()> {
    let problems = conn.quick_check_problems().await?;
    if !problems.is_empty() {
        warn!(
            index,
            ?problems,
            "ticket-title FTS post-rebuild quick_check still reports problems"
        );
    }
    let present = conn
        .upkeep()
        .query_optional(
            "SELECT 1 FROM sqlite_master WHERE type = 'index' AND name = ?1",
            params![index.to_string()],
            |_| Ok::<_, ::turso::Error>(()),
        )
        .await?;
    anyhow::ensure!(
        present.is_some(),
        "rebuilt index '{index}' not found in sqlite_master"
    );
    // MATCH-smoke on a single whitespace-separated token (>= 3 chars,
    // ngram-matchable) taken from a sampled title: a token drawn from a title
    // must match its own row — robust against multi-token titles and titles
    // whose sanitized form is too short to tokenize.
    let titles: Vec<String> = conn
        .upkeep()
        .query_map(
            "SELECT title FROM tickets WHERE title IS NOT NULL AND title != '' LIMIT 16",
            (),
            |row| row.get::<String>(0),
        )
        .await?
        .into_iter()
        .collect::<std::result::Result<Vec<_>, _>>()?;
    let Some((title, term)) = titles.iter().find_map(|title| {
        let sanitized = sanitize_fts_query(title);
        let term = sanitized.split(' ').find(|tok| tok.chars().count() >= 3)?;
        Some((title.clone(), term.to_string()))
    }) else {
        debug!(
            index,
            "no ticket title with an ngram-matchable token — MATCH smoke skipped"
        );
        return Ok(());
    };
    let hit = conn
        .upkeep()
        .query_optional(
            "SELECT id FROM tickets WHERE title MATCH ?1 LIMIT 1",
            params![term.clone()],
            |_| Ok::<_, ::turso::Error>(()),
        )
        .await?;
    anyhow::ensure!(
        hit.is_some(),
        "MATCH smoke failed: token '{term}' from title '{title}' not found via MATCH"
    );
    info!(
        index,
        title, "ticket-title FTS MATCH smoke assertion passed"
    );
    Ok(())
}

/// Drop+CREATE and post-rebuild verification results, returned for callers
/// that need to branch on them (the runtime recovery); the boot path ignores
/// them (all outcomes are logged here, never propagated — fail-safe).
struct TicketTitleFtsRebuildOutcome {
    drop_create: anyhow::Result<()>,
    verified: anyhow::Result<()>,
}

/// Rebuild the ticket-title FTS index from the KNOWN-GOOD DDL (threaded in by
/// the caller), not from `sqlite_master` — the stored DDL of a corrupt index
/// must not be trusted to be the right shape, and the known-good DDL is
/// already threaded in. Mirrors `drop_create_index_fallback`'s transactional
/// DROP+CREATE: a failed CREATE rolls the DROP back, leaving the original
/// index for operator review; ticket rows are never touched. Then verify
/// (filtered quick_check, index presence, MATCH smoke on a known title) and,
/// on request (`reclaim_after_rebuild`), run a WAL checkpoint — successful
/// checkpointing is the observable that the corruption is actually gone. All
/// outcomes logged, never propagated (fail-safe).
///
/// `reclaim_after_rebuild` controls the post-rebuild checkpoint: `true` (boot
/// path, pre-serve, no live writers) runs a TRUNCATE checkpoint so a clean store
/// handoff is observable. `false` skips the internal checkpoint for either of
/// two reasons — the runtime caller re-checkpoints itself right after in the
/// failed attempt's mode (a second back-to-back PASSIVE here would be redundant,
/// and TRUNCATE under live writers is the corruption vector the periodic loop
/// deliberately avoids), or the boot path's pre-shrink gate refused the
/// reclaiming checkpoint.
async fn rebuild_ticket_title_fts(
    conn: &Connection,
    index: &str,
    ddl: &str,
    reclaim_after_rebuild: bool,
) -> TicketTitleFtsRebuildOutcome {
    let quoted = index.replace('"', "\"\"");
    // Transactional DROP+CREATE: a failed CREATE rolls the DROP back via the
    // dropped TxGuard, preserving the original index for operator review
    // (same deferred-rollback discipline as `drop_create_index_fallback`).
    let drop_create = async {
        let tx = conn.begin_tx().await?;
        tx.execute_batch(&format!("DROP INDEX IF EXISTS \"{quoted}\"; {ddl};"))
            .await?;
        tx.commit().await
    }
    .await
    .map_err(anyhow::Error::from);
    let verified = verify_rebuilt_ticket_title_fts(conn, index).await;
    match (&drop_create, &verified) {
        (Ok(()), Ok(())) => {
            info!(index, "ticket-title FTS index rebuilt and verified");
        }
        (drop_create, verified) => {
            warn!(
                index,
                repair_error = ?drop_create.as_ref().err(),
                verify_error = ?verified.as_ref().err(),
                "ticket-title FTS rebuild finished with warnings — check earlier log lines"
            );
        }
    }
    if reclaim_after_rebuild {
        match conn.checkpoint_ungated().await {
            Ok(o) if o.is_complete() => {
                info!(
                    index,
                    checkpointed_frames = o.checkpointed_frames,
                    "post-repair WAL checkpoint complete — corruption cleared"
                );
            }
            Ok(o) => {
                warn!(
                    index,
                    busy = o.busy,
                    log_frames = o.log_frames,
                    checkpointed_frames = o.checkpointed_frames,
                    "post-repair WAL checkpoint incomplete"
                );
            }
            Err(e) => {
                warn!(
                    index,
                    error = %e,
                    "post-repair WAL checkpoint failed"
                );
            }
        }
    }
    TicketTitleFtsRebuildOutcome {
        drop_create,
        verified,
    }
}

/// Boot-time detection + repair of corruption localized to the ticket-title
/// FTS index (incident: recurring "FTS Drop: transaction already committed" /
/// "non-index page" panics and a WAL that never checkpoints). Runs from
/// `BoardStore::after_open` on the consolidated connection, after
/// `ensure_fts_index` and after the class-B open repair (which now vetoes
/// FTS-shaped indexes and delegates here). Idempotent; ticket rows untouched.
///
/// Fail-safe: detection and rebuild are separate `catch_unwind` boundaries
/// (a panicking turso op re-enters the caller via `run_detached`'s
/// `resume_unwind`). A panicking probe is itself corruption evidence — the
/// rebuild is still attempted; a panicking rebuild is logged loudly and boot
/// continues. The instance must never crash-loop over this path, and detection
/// must never be silently skipped.
///
/// The rebuild drops and recreates the index, so it holds the store's readers
/// off exactly as the runtime repair does ([`Connection::quiet_readers`]; see
/// [`repair_ticket_title_fts_runtime`] for why a reader must not be in flight
/// under an index move). At this point in the open nothing has read yet, so the
/// guard is free; a reader that does not fall idle in time leaves the repair to
/// the runtime round (`Deferred` there), which is where a boot that cannot take
/// the store quiet also leaves it.
///
/// `store` and `root` are the refusal record's identity and artifact directory:
/// the post-rebuild TRUNCATE is a reclaiming checkpoint, so it passes the
/// pre-shrink gate first (see [`crate::db::shrink_gate`]), and a refusal means
/// the rebuild runs without shrinking. The probe necessarily runs BEFORE the
/// DROP+CREATE rebuild (the gate guards the checkpoint at the end of it), so a
/// refusal blocks a round in which no reclaiming checkpoint may ever be issued
/// (the rebuild itself may then fail or find nothing to do), and the page count
/// it judges can be one rebuild older than the checkpoint it guards — the
/// documented pre-check window, with the refusal cost being one conservative
/// skipped shrink.
pub(crate) async fn repair_ticket_title_fts_if_corrupt(
    conn: &Connection,
    index: &str,
    ddl: &str,
    store: &'static str,
    root: Option<&Path>,
) {
    let detected = AssertUnwindSafe(detect_ticket_title_fts_corruption(conn, index))
        .catch_unwind()
        .await;
    let evidence = match detected {
        Ok(Ok(evidence)) => evidence,
        Ok(Err(e)) => {
            error!(
                index,
                error = %e,
                "ticket-title FTS boot probe failed — boot continues; index left as-is for operator review"
            );
            return;
        }
        Err(panic) => {
            warn!(
                index,
                panic = %crate::util::panic_message(&panic),
                "ticket-title FTS boot probe panicked — treating as corruption evidence, attempting the rebuild"
            );
            Some("detection probe panicked".to_string())
        }
    };
    let Some(evidence) = evidence else {
        info!(
            index,
            "ticket-title FTS boot probe: index healthy — no repair"
        );
        return;
    };
    warn!(
        index,
        evidence = %evidence,
        "ticket-title FTS corruption signature detected at boot — rebuilding the index (ticket rows untouched)"
    );
    // The rebuild drops and recreates the index: take the readers out of service
    // for it (see this function's doc) and keep them out through the
    // post-rebuild checkpoint, whose TRUNCATE a held reading position would
    // answer busy. A reader that does not fall idle in time leaves the repair to
    // the runtime round rather than running it under a live reader.
    let Some(_quiet) = conn.quiet_readers().await else {
        warn!(
            index,
            "the store's readers did not fall idle — leaving the index as it is; the periodic \
             round retries this repair"
        );
        return;
    };
    // The post-rebuild TRUNCATE is the reclaiming checkpoint this gate
    // protects; a refusal means the rebuild runs without shrinking.
    let reclaim_after_rebuild = crate::db::shrink_gate::shrink_allowed(conn, store, root).await;
    let rebuilt = AssertUnwindSafe(rebuild_ticket_title_fts(
        conn,
        index,
        ddl,
        reclaim_after_rebuild,
    ))
    .catch_unwind()
    .await;
    if let Err(panic) = rebuilt {
        error!(
            index,
            panic = %crate::util::panic_message(&panic),
            "ticket-title FTS boot repair panicked — boot continues; index left as-is for operator review"
        );
    }
}

/// Outcome of the runtime (periodic-round) ticket-title FTS repair.
#[derive(Debug)]
pub(crate) enum TicketTitleFtsRuntimeRepair {
    /// Store carries no ticket-title FTS index — nothing to repair.
    NotApplicable,
    /// Index present and healthy — nothing about this attempt was FTS-attributable.
    Healthy,
    /// Corruption detected and the rebuild ran; payload summarizes detection
    /// evidence and repair outcome for the caller's report.
    Rebuilt(String),
    /// The repair was not attempted: the store's readers did not fall idle, so
    /// the rebuild could not be run with the store quiet. Reported as itself,
    /// never as a failure — the next round tries again.
    Deferred(String),
    /// Detection errored/panicked or the rebuild panicked — repair incomplete.
    Failed(String),
}

impl TicketTitleFtsRuntimeRepair {
    /// Compact human-readable summary for the failure report (the enum's
    /// derived Debug keeps the shape but is not report-friendly). Reads the
    /// payload variants so the detection/repair evidence is surfaced.
    #[must_use]
    pub(crate) fn summary(&self) -> String {
        match self {
            Self::NotApplicable => "not applicable (no ticket-title FTS index)".to_string(),
            Self::Healthy => "healthy (index present, probe clean)".to_string(),
            Self::Rebuilt(evidence) => format!("rebuilt after detection — {evidence}"),
            Self::Deferred(reason) => format!("deferred — {reason}"),
            Self::Failed(reason) => format!("failed — {reason}"),
        }
    }
}

/// The periodic round's variant of the boot-time ticket-title FTS repair: invoked
/// after a first attempt that failed or was answered busy. Runs the same boot
/// primitives (see [`repair_ticket_title_fts_if_corrupt`]) — detection and the
/// drop+recreate rebuild — via its own wrapper so the post-rebuild checkpoint
/// mode and the caller-visible outcome can differ from the boot path.
/// Execution is synchronous and holds the writing connection, so the store
/// serves nothing else while the repair runs — acceptable for this rare recovery
/// path. Its statements are ordinary statements: the per-statement limit applies
/// to the rebuild exactly as to everything else, and a rebuild that outran it is
/// cut like any other statement. The `sqlite_master` presence check
/// first makes stores that carry no ticket-title FTS index (e.g. logs.db)
/// no-ops. Panics use the same `catch_unwind` discipline as the boot path.
///
/// # Readers
///
/// The rebuild drops and recreates the index inside one transaction, and its
/// premise is that nothing else is in flight against the store. The writing
/// connection's own mutex gives that for writers and checkpoints; the readers
/// are the one thing it does not cover, so they are taken out of service and
/// closed first ([`Connection::quiet_readers`]) — reads keep being served, by
/// the writing connection, and the next read after the repair creates fresh
/// readers. A reader that does not fall idle in time defers the whole repair to
/// a later round (`Deferred`) rather than running it against live readers: a
/// reader is never invalidated on the assumption that the engine would notice
/// the index move under it.
pub(crate) async fn repair_ticket_title_fts_runtime(
    conn: &Connection,
) -> TicketTitleFtsRuntimeRepair {
    let Some(_quiet) = conn.quiet_readers().await else {
        return TicketTitleFtsRuntimeRepair::Deferred(
            "reader connections did not fall idle".to_string(),
        );
    };
    // Absent index → nothing to repair (non-domain stores never carry it).
    // Panic-guarded like every probe on this path: a turso panic must become
    // this repair's own `Failed` outcome, never escape to the outer per-store
    // catch and skip the checkpoint round's record-and-stop.
    let present = AssertUnwindSafe(conn.upkeep().query_optional(
        "SELECT 1 FROM sqlite_master WHERE type = 'index' AND name = ?",
        params![TICKETS_FTS_INDEX_NAME.to_string()],
        |_| Ok::<_, ::turso::Error>(()),
    ))
    .catch_unwind()
    .await;
    let present = match present {
        Ok(Ok(present)) => present,
        Ok(Err(e)) => {
            return TicketTitleFtsRuntimeRepair::Failed(format!(
                "index presence probe failed: {e}"
            ));
        }
        Err(panic) => {
            return TicketTitleFtsRuntimeRepair::Failed(format!(
                "index presence probe panicked: {}",
                crate::util::panic_message(&panic)
            ));
        }
    };
    if present.is_none() {
        return TicketTitleFtsRuntimeRepair::NotApplicable;
    }

    let detected = AssertUnwindSafe(detect_ticket_title_fts_corruption(
        conn,
        TICKETS_FTS_INDEX_NAME,
    ))
    .catch_unwind()
    .await;
    let evidence = match detected {
        // Present and probe-clean → nothing about this attempt was FTS-shaped.
        Ok(Ok(None)) => return TicketTitleFtsRuntimeRepair::Healthy,
        Ok(Ok(Some(evidence))) => evidence,
        Ok(Err(e)) => {
            return TicketTitleFtsRuntimeRepair::Failed(format!("detection probe failed: {e}"));
        }
        // A panicking probe is itself corruption evidence (boot precedent) —
        // attempt the rebuild.
        Err(panic) => format!(
            "detection probe panicked: {}",
            crate::util::panic_message(&panic)
        ),
    };

    let rebuilt = AssertUnwindSafe(rebuild_ticket_title_fts(
        conn,
        TICKETS_FTS_INDEX_NAME,
        TICKETS_FTS_INDEX_DDL,
        false,
    ))
    .catch_unwind()
    .await;
    let TicketTitleFtsRebuildOutcome {
        drop_create,
        verified,
    } = match rebuilt {
        Ok(outcome) => outcome,
        Err(panic) => {
            return TicketTitleFtsRuntimeRepair::Failed(format!(
                "rebuild panicked: {}; evidence: {evidence}",
                crate::util::panic_message(&panic)
            ));
        }
    };
    if drop_create.is_err() || verified.is_err() {
        return TicketTitleFtsRuntimeRepair::Failed(format!(
            "rebuild incomplete: drop_create error: {:?}; verify error: {:?}; evidence: {evidence}",
            drop_create.as_ref().err(),
            verified.as_ref().err(),
        ));
    }
    // The rebuild logs its own verification (verify_rebuilt warns on residual
    // quick_check problems) and the caller's terminal report runs its own
    // panic-guarded quick_check — no extra probe here, keeping this path
    // panic-free by construction.
    TicketTitleFtsRuntimeRepair::Rebuilt(format!("corruption detected: {evidence}"))
}

// Any schema creation, change, or removal is an entry in the append-only
// catalog (see [`crate::db::migrations`]); the only tracking mechanism is the
// id-based applied check in [`crate::db::migrations::run_migrations`].

/// Open a database, create parent directories if needed, and run schema init.
///
/// `schema` is executed via `execute_batch` (multiple DDL statements).
pub(crate) async fn open_with_schema(db_path: &Path, schema: &str) -> anyhow::Result<Connection> {
    if let Some(parent) = db_path.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("Failed to create directory: {}", parent.display()))?;
    }

    let conn = Connection::open(db_path)
        .await
        .with_context(|| format!("Failed to open database: {}", db_path.display()))?;

    conn.execute("PRAGMA foreign_keys = ON;", ())
        .await
        .context("Failed to enable foreign key enforcement")?;

    // Never embed the DDL in the error: a multi-kilobyte schema string hides
    // the engine's actual reason (e.g. `no such column: ticket_id`) and was
    // how a schema-DDL failure against a readable store went undiagnosed.
    execute_schema_ddl(&conn, schema).await?;

    Ok(conn)
}

/// Run a schema batch. The source Turso error is the context's cause — do not
/// interpolate `sql` into the message (see [`open_with_schema`]).
async fn execute_schema_ddl(conn: &Connection, sql: &str) -> anyhow::Result<()> {
    if sql.trim().is_empty() {
        return Ok(());
    }
    conn.execute_batch(sql)
        .await
        .context("Failed to run schema DDL")?;
    Ok(())
}

/// Resolve a logical store name to its physical database file path.
///
/// # Consolidated layout
///
/// The domain stores (`DOMAIN_STORE_NAMES`) are consolidated into ONE file
/// ([`CONSOLIDATED_DB_NAME`]); the logs store remains its own file. So this
/// function maps every domain name (and the canonical
/// [`CONSOLIDATED_DB_NAME`] itself) to `root/db/{CONSOLIDATED_DB_NAME}.db`, and
/// [`LOG_DB_NAME`] to `root/db/{LOG_DB_NAME}.db`.
#[must_use]
pub(crate) fn store_db_path(root: &Path, name: &str) -> std::path::PathBuf {
    let stem = if name == LOG_DB_NAME {
        LOG_DB_NAME
    } else {
        CONSOLIDATED_DB_NAME
    };
    store_dir(root).join(format!("{stem}.db"))
}

/// The store directory of a storage root — where both physical stores live,
/// together with the recovery copies the service keeps of them. The one place
/// the layout is spelled: a rule that decides anything by location (the
/// live-store refusal, the forensic listing) asks here rather than joining
/// `db` itself.
#[must_use]
pub(crate) fn store_dir(root: &Path) -> std::path::PathBuf {
    root.join("db")
}

/// The marker a rebuild's own temp file carries — `{store}.db.rebuild-{stamp}`,
/// written beside the store it is rebuilding. The tool guard recognises a
/// rebuild temp as one of the service's own files by it, so it is spelled once,
/// here, beside the writer.
pub(crate) const REBUILD_TEMP_MARKER: &str = ".rebuild-";

/// The `-wal` sidecar path of a store's database file. The WAL is the engine's
/// own: it can hold committed-but-uncheckpointed frames, so it is moved aside
/// with the store by the quarantine and by the rebuild swap, and it is never
/// deleted while it might hold them.
#[must_use]
pub(crate) fn wal_path(db_path: &Path) -> std::path::PathBuf {
    std::path::PathBuf::from(format!("{}-wal", db_path.display()))
}

/// Resource/permission keywords for [`is_actionable_signal`]: actionable
/// conditions (never damage) — ENOSPC/EMFILE/OOM/permission must not be
/// reported as a repair finding.
const RESOURCE_SIGNAL_KEYWORDS: [&str; 4] = [
    "no space left on device",
    "too many open files",
    "out of memory",
    "permission denied",
];

fn has_resource_signal(lower: &str) -> bool {
    RESOURCE_SIGNAL_KEYWORDS.iter().any(|k| lower.contains(k))
}

/// Lock/busy contention keywords for [`is_actionable_signal`]. The engine
/// reports another process holding a store as the open-time whole-file lock
/// (the `Locking error:` step marker, whatever the platform's contention
/// wording — see [`is_open_time_lock_error`]), a locked table, or a busy
/// database. All of them are one external condition — never damage, and never
/// silently ignored.
const LOCK_SIGNAL_KEYWORDS: [&str; 3] = ["locking", "locked", "busy"];

fn has_lock_signal(lower: &str) -> bool {
    LOCK_SIGNAL_KEYWORDS.iter().any(|k| lower.contains(k))
}

/// True when a failure is an actionable signal: a resource/permission condition
/// (ENOSPC/EMFILE/OOM/permission) or lock contention with another process (the
/// engine's open-time file lock, a locked table, a busy database). Neither is
/// damage, so the repair path propagates them loud rather than reporting a
/// spurious repair finding, and the durable failure record marks them as
/// environment-caused.
pub(crate) fn is_actionable_signal(e: &anyhow::Error) -> bool {
    text_is_actionable_signal(&format!("{e:#}"))
}

/// [`is_actionable_signal`] over an already-rendered message — for callers that
/// hold probe text rather than a rendered error chain.
pub(crate) fn text_is_actionable_signal(text: &str) -> bool {
    let lower = text.to_lowercase();
    has_resource_signal(&lower) || has_lock_signal(&lower)
}

/// Open a store database under `<root>/db/<name>.db` (path built by
/// [`store_db_path`]).
///
/// The bring-up gate lives here. An absent data file is a genuine first launch:
/// the store is created (the only path that builds a schema in place of
/// nothing). An existing file must pass the file-level shape check
/// ([`crate::db::wal_guard::classify_store_shape`]) and then open AND carry the
/// product's own schema, otherwise the call refuses with a [`StoreRefusal`] and
/// leaves the file exactly as it is. The data-preserving repairs still run on an
/// opened store; only a repair that *fails* refuses — a condition the repairs
/// deliberately leave report-only (an unknown quick_check signature) opens the
/// store exactly as it does today. Per-store `open()` constructors are generated
/// by [`crate::define_store!`] on top of [`open_consolidated_store`] (which calls
/// this function for the consolidated file).
pub(crate) async fn open_store(
    root: &Path,
    name: &'static str,
    schema: &str,
) -> anyhow::Result<Connection> {
    let db_path = store_db_path(root, name);
    match crate::db::wal_guard::classify_store_shape(&db_path) {
        // No data file — a genuine first launch. Creating the store is the only
        // path that builds a schema in place of nothing.
        crate::db::wal_guard::StoreShape::Absent => open_with_schema(&db_path, schema).await,
        crate::db::wal_guard::StoreShape::Unusable(defect) => {
            Err(StoreRefusal::new(name, &db_path, defect.reason())
                .with_environment(defect.is_environment_caused())
                .into())
        }
        crate::db::wal_guard::StoreShape::Present => {
            let opened = AssertUnwindSafe(open_present_store(root, &db_path, name, schema))
                .catch_unwind()
                .await;
            match opened {
                Ok(result) => result,
                // turso's own reopen of a damaged store can panic; a panic is a
                // refusal, not a reason to replace the file.
                Err(payload) => Err(StoreRefusal::new(
                    name,
                    &db_path,
                    format!("open panicked: {}", crate::util::panic_message(&*payload)),
                )
                .into()),
            }
        }
    }
}

/// Open an existing, shape-valid store: require it to open and to carry the
/// product's own schema, then run the data-preserving repairs. Every failure is
/// a refusal — the store is never quarantined, recreated or emptied.
async fn open_present_store(
    root: &Path,
    db_path: &Path,
    name: &'static str,
    schema: &str,
) -> anyhow::Result<Connection> {
    let conn = match open_with_schema(db_path, schema).await {
        Ok(conn) => conn,
        // A resource/permission/lock condition is environmental, never store
        // damage; it propagates unwrapped so the boot recorder names it (the lock
        // case with its own wording) and records it with the environment note.
        Err(e) if is_actionable_signal(&e) => return Err(e),
        Err(e) => {
            return Err(
                StoreRefusal::new(name, db_path, format!("it could not be opened: {e:#}")).into(),
            );
        }
    };
    match has_product_schema(&conn).await {
        Ok(true) => {}
        Ok(false) => {
            return Err(StoreRefusal::new(
                name,
                db_path,
                "it opens but does not carry the product's own schema",
            )
            .into());
        }
        // Environmental, like an open failure — never recorded as damage.
        Err(e) if is_actionable_signal(&e) => return Err(e),
        Err(e) => {
            return Err(StoreRefusal::new(
                name,
                db_path,
                format!("the schema probe failed: {e:#}"),
            )
            .into());
        }
    }
    run_repairs(conn, root, db_path, name, schema).await
}

/// True when an opened store carries the product's own schema — the ledger every
/// install of this product writes ([`crate::db::migrations::MIGRATIONS_TABLE`]).
/// A present store without it was never built by the product (an empty file, a
/// foreign SQLite file, or a store left before its first catalog run) and must
/// not have a schema built inside it.
///
/// The ledger is the marker for every install this product ever created (the
/// catalog has owned it since before the retired `1`–`23` chain), so an older
/// install is not refused: it carries the ledger and migrates as usual.
async fn has_product_schema(conn: &Connection) -> anyhow::Result<bool> {
    let table = crate::db::migrations::MIGRATIONS_TABLE;
    let ledger: Option<i64> = conn
        .query_optional(
            &format!(
                "SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name = '{table}'"
            ),
            (),
            |row| row.get::<i64>(0),
        )
        .await?;
    if ledger.unwrap_or(0) == 0 {
        return Ok(false);
    }
    let recorded: i64 = conn
        .query_row(&format!("SELECT COUNT(*) FROM {table}"), (), |row| {
            row.get::<i64>(0)
        })
        .await?;
    Ok(recorded > 0)
}

/// Run the data-preserving repairs on an opened store. Only outcomes that used
/// to fall back to moving the store aside and recreating it are refusals now;
/// every repair that preserves the data keeps handling exactly what it handles
/// today.
async fn run_repairs(
    conn: Connection,
    root: &Path,
    db_path: &Path,
    name: &'static str,
    schema: &str,
) -> anyhow::Result<Connection> {
    match repair_btree_index_if_desynced(conn, root, db_path, name, schema).await {
        Ok((RepairOutcome::Unreadable, _conn)) => {
            Err(StoreRefusal::new(name, db_path, "its integrity check cannot read a table").into())
        }
        Ok((_, conn)) => Ok(conn),
        // A resource/permission/lock condition is environmental, never store
        // damage: propagate it unwrapped so it is recorded (and shown) as the
        // condition it is, not as an unusable store.
        Err(e) if is_actionable_signal(&e) => Err(e),
        // Only a data-preserving rebuild that could not complete reaches here:
        // the original family is preserved or quarantined for recovery and the
        // store is refused, never replaced with an empty one.
        Err(e) => Err(StoreRefusal::new(
            name,
            db_path,
            format!("the data-preserving rebuild could not be completed: {e:#}"),
        )
        .into()),
    }
}

/// Open (or create) the single consolidated domain database file.
///
/// This is the canonical open for the domain stores: it opens the one
/// consolidated file ([`store_db_path`] mapping all domain names to
/// [`CONSOLIDATED_DB_NAME`]) and applies the append-only schema catalog
/// ([`crate::db::migrations`]) — the single owner of every schema creation,
/// change, and removal for core.db. It does NOT run the per-store post-open
/// hooks (tickets FTS index, admin-user seed) — those are idempotent and run
/// in [`init_all_stores`] (production) and each store's `open` (isolated
/// tests).
///
/// # Catalog, not SCHEMA
///
/// The catalog is a current-shape baseline: the entries create the exact
/// current schema directly (every statement `IF NOT EXISTS`), so a fresh
/// install converges in one pass and an existing install is a no-op except
/// the upfill deltas. The baseline ids, the upfill deltas, and the resume
/// point live in the [`crate::db::migrations`] module doc — the single owner
/// of that list. The only control flow is the id-based applied check (skip if
/// the id is already recorded, otherwise run and record). A catalog failure
/// is a hard boot failure — it is never a repair finding and never a reason
/// to replace the store.
///
/// # Why tables → ALTER → indexes is baked into the catalog order
///
/// The historical incident was real: SCHEMA gained `CREATE UNIQUE INDEX … ON
/// jobs(kind, ticket_id)` while `ticket_id` was only added by a later ALTER.
/// `CREATE TABLE IF NOT EXISTS jobs` left the old table unchanged; the index
/// failed with `no such column` and the store was misclassified as corruption
/// and rebuilt empty. In the baseline, `jobs` is created WITH `ticket_id`, so
/// `idx_jobs_phase_ticket` is safe to create in the same batch.
///
/// Returns a **fresh** connection. Production shares it across all domain
/// stores via [`DOMAIN_CONN`]; isolated test opens (`open_test_store!`) drop it
/// with the store. There is deliberately no process-global cache here so test
/// isolation never leaks a connection across roots.
pub(crate) async fn open_consolidated_store(root: &Path) -> anyhow::Result<Connection> {
    // The catalog owns the ENTIRE schema. Open the raw connection (no DDL) and
    // run the catalog; a catalog failure is a hard boot error — never a repair
    // finding and never a reason to replace the store. A fresh store is empty
    // until the catalog builds the full current shape.
    let conn = open_store(root, CONSOLIDATED_DB_NAME, "").await?;
    migrations::run_migrations(&conn, migrations::TargetDb::Core).await?;

    // Enable CDC on the FINAL connection, after all migrations, so
    // boot-time schema writes are not captured. This single chokepoint covers
    // the boot open and the test-store opens (open_test_store! and
    // init_test_stores both call open_consolidated_store).
    cdc::enable_capture(&conn).await?;

    // The store is final now — nothing past this point replaces or rebuilds its
    // file — so its reads may be served by reader connections of their own.
    // (The log store is opened by `logs::init_tracing`, never here, and keeps
    // its own writing connection without readers.)
    conn.enable_readers();

    Ok(conn)
}

/// Outcome of the class-B btree-index repair.
enum RepairOutcome {
    /// No repair needed: quick_check passed, or a report-only condition
    /// (unknown signature / failed in-place repair / aborted rebuild left for
    /// operator review). The store opens normally either way.
    NoRepair,
    /// REINDEX (or the DROP+CREATE fallback) cleared the desync.
    Repaired,
    /// Overflow-aliasing: the store's data was rebuilt in a fresh file and
    /// swapped into place (the in-file DROP of the aliased b-trees would
    /// double-free the shared overflow page and re-corrupt the freelist).
    /// The returned connection is the reopened, verified store.
    Migrated,
    /// The table is unreadable (quick_check scan failure) — the store is
    /// refused, never recreated.
    Unreadable,
}

/// Open a raw-DDL fixture store and run the repair half of the existing-store
/// open (the boot path additionally requires the product-schema ledger, which
/// these fixtures are built without).
#[cfg(test)]
async fn open_and_repair_for_test(
    root: &Path,
    db_path: &Path,
    name: &'static str,
    schema: &str,
) -> anyhow::Result<Connection> {
    let conn = open_with_schema(db_path, schema).await?;
    run_repairs(conn, root, db_path, name, schema).await
}

/// The baked overflow-aliasing signature: a prior REINDEX/DROP+CREATE on a
/// store whose index leaves shared an overflow page left the page doubly on
/// the freelist, so a later allocation reuses it as both a b-tree page and an
/// overflow chain; reading that chain yields this exact short-read on every
/// scan. The table stays readable there — the store is rebuilt
/// data-preservingly in a fresh sibling file, never recreated empty.
const BAKED_OVERFLOW_ALIASING_READ: &str = "short read on page 167772160";

/// What the class-B repair should do given the full quick_check problem list.
enum RepairTarget {
    /// The table cannot be scanned ("Invalid page type"/"short read") — the
    /// store is refused.
    Unreadable,
    /// Shared overflow pages between index leaves (fresh "Page N referenced
    /// multiple times" or the baked short-read) — never REINDEX (bakes a
    /// worse error); rebuild the store data-preservingly.
    OverflowAliasing,
    /// A specific non-FTS btree index is desynced — in-place repair.
    Index(String),
    /// No recognizable signature — report only.
    Unknown,
}

/// Classify the full quick_check problem list for the class-B repair.
///
/// Ordering is deliberate and structural: unreadable-table signatures win
/// over everything (the table cannot be scanned at all); overflow-aliasing
/// anywhere in the list vetoes the REINDEX even when an earlier row names an
/// index desync (quick_check can surface both in one scan — the veto must not
/// depend on row order). The baked short-read (page 0x0A000000) is an
/// overflow-aliasing marker, not a table-read failure — the generic short-read
/// check comes after it.
fn classify_repair_target(problems: &[String]) -> RepairTarget {
    if problems.iter().any(|p| p.contains("Invalid page type")) {
        RepairTarget::Unreadable
    } else if problems.iter().any(|p| {
        p.contains("referenced multiple times") || p.contains(BAKED_OVERFLOW_ALIASING_READ)
    }) {
        RepairTarget::OverflowAliasing
    } else if problems.iter().any(|p| p.contains("short read")) {
        RepairTarget::Unreadable
    } else {
        match problems.iter().find_map(|p| desynced_index_name(p)) {
            Some(index) => RepairTarget::Index(index.to_string()),
            None => RepairTarget::Unknown,
        }
    }
}

/// True when a filtered `quick_check` problem list names only conditions the
/// boot path deliberately leaves report-only (an unrecognised signature) rather
/// than damage it acts on (repair or refusal). The runtime integrity record uses
/// this so a tolerated finding is never filed as damage.
#[must_use]
pub(crate) fn is_tolerated_integrity_report(problems: &[String]) -> bool {
    matches!(classify_repair_target(problems), RepairTarget::Unknown)
}

/// Pre-repair forensic snapshot path (engine-produced):
/// `{db}.pre-reindex-{stamp}-{pid}`. The base name must stay parseable by
/// `debug::parse_family_name` — the writer round-trip test locks the coupling.
#[must_use]
fn pre_reindex_snapshot_path(db_path: &Path) -> std::path::PathBuf {
    std::path::PathBuf::from(format!(
        "{}.pre-reindex-{}",
        db_path.display(),
        family_stamp()
    ))
}

/// Forensic pre-repair snapshot of a store, produced BY THE ENGINE
/// (`VACUUM INTO`) rather than copied with `fs::copy`: copying opens the store's
/// main file, which wal_guard's lock rule forbids in the running service. It
/// leaves an empty `<dest>-wal` beside the copy, so the forensic family stays
/// db + wal. Two accepted consequences: the artifact is a logical copy, not the
/// store's original bytes, and a store the engine cannot vacuum gets no snapshot
/// at all — the caller only warns, since the artifact exists for the
/// REINDEX-bakes-a-worse-error case and an engine that cannot read the store
/// cannot REINDEX it either.
///
/// Panic-absorbed: the vacuum walks every btree of an already-damaged store,
/// which is exactly where the engine can panic, and a panic must not unwind boot
/// for missing evidence.
async fn snapshot_store_via_engine(
    conn: &Connection,
    db_path: &Path,
) -> anyhow::Result<std::path::PathBuf> {
    let dest = pre_reindex_snapshot_path(db_path);
    // `VACUUM INTO` takes a SQL string literal (no bind parameter), so the
    // path is single-quote escaped.
    let escaped = dest.display().to_string().replace('\'', "''");
    // `Connection::execute` routes through `run_detached`, which holds the
    // connection mutex for the whole statement — no other statement is active on
    // the writing connection. (The store's readers, in service by the time the
    // store-lock check runs this, are statements of their own on their own
    // connections.)
    match AssertUnwindSafe(conn.execute(&format!("VACUUM INTO '{escaped}'"), ()))
        .catch_unwind()
        .await
    {
        Ok(Ok(_)) => Ok(dest),
        Ok(Err(e)) => {
            Err(anyhow::Error::from(e).context(format!("VACUUM INTO {}", dest.display())))
        }
        Err(payload) => Err(anyhow::anyhow!(
            "VACUUM INTO {} panicked: {}",
            dest.display(),
            crate::util::panic_message(&*payload)
        )),
    }
}

/// Class-B btree-index desync repair: `quick_check` names a specific
/// non-FTS index → REINDEX in place, DROP+CREATE as the fallback (both
/// validated on the 324MB prod sessions copy — both M>N and M<N desync forms,
/// survives reopen and TRUNCATE). Returns `Ok(([`RepairOutcome`], conn))`; an
/// actionable quick_check failure (ENOSPC/EMFILE/permission, or lock
/// contention) propagates as `Err` — it is a signal, never a repair finding.
///
/// Preconditions are satisfied by construction at boot: single-writer,
/// exclusive access, and a snapshot (engine-produced `VACUUM INTO`) taken before
/// the REINDEX. The overflow-aliasing signature ("referenced multiple times" /
/// shared overflow pages, fresh or baked as "short read on page 167772160") is
/// **never** REINDEXed — that bakes a worse error; the store is rebuilt
/// data-preservingly instead (see [`migrate_overflow_aliased_store`]).
/// Unreadable tables surface as quick_check scan failures ("Invalid page
/// type"/"short read") and refuse the store.
async fn repair_btree_index_if_desynced(
    conn: Connection,
    root: &Path,
    db_path: &Path,
    name: &'static str,
    schema: &str,
) -> anyhow::Result<(RepairOutcome, Connection)> {
    // All problem rows, not just the first: quick_check can surface a named
    // index desync in one row and overflow-aliasing in another — the
    // overflow-aliasing veto must hold regardless of row order.
    let problems = match conn.quick_check_problems().await {
        Ok(p) if p.is_empty() => return Ok((RepairOutcome::NoRepair, conn)),
        Ok(p) => p,
        Err(e) => {
            // The quick_check itself failed to run — an actionable signal
            // (resource/permission condition or lock contention) is never a
            // repair finding; propagate it.
            if is_actionable_signal(&e) {
                return Err(e);
            }
            crate::boot::boot_diagnostic(format!(
                "store '{name}' quick_check could not run: {e} — unreadable table; the \
                 store is refused",
            ));
            return Ok((RepairOutcome::Unreadable, conn));
        }
    };
    let index = match classify_repair_target(&problems) {
        RepairTarget::Unreadable => {
            crate::boot::boot_diagnostic(format!(
                "store '{name}' quick_check cannot scan a table ({}) — unreadable table; \
                 the store is refused",
                problems.join("; "),
            ));
            return Ok((RepairOutcome::Unreadable, conn));
        }
        // Overflow-aliasing (shared overflow pages between index leaves) must
        // NEVER be REINDEXed — that bakes a worse error ("short read on
        // page …"). Structural veto: checked across the whole problem list.
        RepairTarget::OverflowAliasing => {
            crate::boot::boot_diagnostic(format!(
                "store '{name}' quick_check reports overflow-aliasing ({}) — rebuilding \
                 the store data-preservingly in a fresh file",
                problems.join("; "),
            ));
            return migrate_overflow_aliased_store(conn, root, db_path, name, schema).await;
        }
        // Report-only by decision: an unrecognised quick_check signature is not
        // proof that the data is unusable, so the store boots exactly as it does
        // today — never a refusal, and never a rebuild over the operator's data.
        RepairTarget::Unknown => {
            crate::boot::boot_diagnostic(format!(
                "store '{name}' quick_check flagged an unknown condition: {}",
                problems.join("; "),
            ));
            return Ok((RepairOutcome::NoRepair, conn));
        }
        RepairTarget::Index(index) => {
            // Belt-and-braces: unreachable today (`scan_integrity_rows` filters
            // the exact FTS count-mismatch row before this list is built), but
            // never REINDEX the out-of-scope FTS internal index if a future
            // filter change lets it through.
            if known_fts_dir_false_positive(&index) {
                crate::boot::boot_diagnostic(format!(
                    "store '{name}' quick_check flagged the known FTS false positive — \
                     not repairing",
                ));
                return Ok((RepairOutcome::NoRepair, conn));
            }
            // FTS indexes are never rebuilt in place here: REINDEX/DROP+CREATE on
            // the FTS backing dir is the documented "FTS Drop" panic class, and
            // the dedicated boot repair (`repair_ticket_title_fts_if_corrupt`, run
            // from BoardStore::after_open) owns FTS rebuilds. Leave the desync
            // reported.
            if is_fts_index(&conn, &index).await {
                crate::boot::boot_diagnostic(format!(
                    "store '{name}' quick_check flagged FTS index '{index}' — in-place repair \
                     out of scope; the after_open FTS repair owns its rebuild",
                ));
                return Ok((RepairOutcome::NoRepair, conn));
            }
            index
        }
    };
    // Forensic snapshot before the in-place repair, produced by the engine
    // rather than copied (see [`snapshot_store_via_engine`] for why). Best
    // effort: the snapshot is evidence, not a precondition for the repair.
    if let Err(e) = snapshot_store_via_engine(&conn, db_path).await {
        warn!("Failed to write pre-reindex snapshot: {e:#}");
    }
    // REINDEX rewrites the index btree in place. Quoting: identifiers may
    // contain special characters.
    let quoted = index.replace('"', "\"\"");
    if conn
        .execute_batch(&format!("REINDEX \"{quoted}\";"))
        .await
        .is_ok()
        && conn.quick_check().await.is_ok()
    {
        info!(
            db = %name,
            index = %index,
            "class-B btree index desync repaired in place (REINDEX)",
        );
        return Ok((RepairOutcome::Repaired, conn));
    }
    crate::boot::boot_diagnostic(format!(
        "store '{name}' REINDEX of '{index}' did not clear the quick_check desync — \
         falling back to DROP+CREATE",
    ));
    Ok((
        drop_create_index_fallback(&conn, name, &index, &quoted).await,
        conn,
    ))
}

/// Row count of a table by name (the identifier is quoted inside). Both
/// callers in [`migrate_overflow_aliased_store`] own their per-site error
/// handling — the pre-count's unreadable-table classification and the
/// post-swap verification's actionable-signal split differ by site, so the
/// helper only centralises the quoted `SELECT COUNT(*)` shape.
async fn count_table_rows(conn: &Connection, table: &str) -> turso::Result<i64> {
    let quoted = table.replace('"', "\"\"");
    conn.query_row(&format!("SELECT COUNT(*) FROM \"{quoted}\""), (), |r| {
        r.get::<i64>(0)
    })
    .await
}

/// Overflow-aliasing repair: rebuild the store's data in a fresh sibling file,
/// verify it, then swap it into place. The in-file alternative (DROP the
/// aliased b-trees and recreate) double-frees the shared overflow page — the
/// free-walk frees it once per referencing leaf — corrupting the freelist, so
/// the rebuilt store re-aliases on the next allocation (the "baked short read"
/// mechanism). A fresh file is the only path that verifies clean (index valid,
/// data intact).
///
/// Preconditions hold at boot: single-writer, exclusive access before any
/// live traffic. The original family is quarantined (renamed aside, never
/// deleted — the forensic record) before the swap, so the original data is
/// preserved even when the rebuild aborts. Returns
/// `Ok(([`RepairOutcome::Migrated`], reopened))` on success. Before the swap a
/// constraint violation during the data copy (a data-integrity finding, not
/// damage) or a fresh store that cannot be built leaves the original untouched
/// and reports only (`NoRepair`). A table that cannot be read propagates as
/// `Err` (the store is refused). A swap that could not complete — a partial
/// quarantine with the main file already moved, a failed main-file rename, or a
/// rebuilt store that will not reopen — propagates as `Err`, which refuses the
/// store rather than replacing it with an empty one. Actionable resource
/// conditions (ENOSPC/EMFILE/permission) also propagate as `Err`.
#[expect(clippy::too_many_lines)] // one linear boot-repair flow, split across helpers
async fn migrate_overflow_aliased_store(
    conn: Connection,
    root: &Path,
    db_path: &Path,
    name: &'static str,
    schema: &str,
) -> anyhow::Result<(RepairOutcome, Connection)> {
    // multiprocess_wal was removed: there is no shared WAL frame index to reset
    // before a rebuild.

    // ── Readability + row-count per user table (quick_check does not name
    // the aliased index, so every table's read is gated; unreadable →
    // the store is refused). `__turso_internal_%` tables reject user writes and
    // are recreated by the DDL replay — excluded from the copy + verification.
    let mut counts: Vec<(String, i64)> = Vec::new();
    let tables = match conn
        .query(
            &format!(
                "SELECT name FROM sqlite_master WHERE type='table' \
                 AND {USER_OBJECT_FILTER} ORDER BY rowid"
            ),
            (),
        )
        .await
    {
        Ok(t) => t,
        // A table-enumeration failure is an engine-level read problem, not
        // proof the data is unreadable — report-only (conservative, no data
        // loss), unlike the per-table read below which refuses the store.
        Err(e) => {
            let err = anyhow::anyhow!(e);
            if is_actionable_signal(&err) {
                return Err(err);
            }
            crate::boot::boot_diagnostic(format!(
                "store '{name}' cannot enumerate tables for the rebuild: {err} — left \
                 for operator review",
            ));
            return Ok((RepairOutcome::NoRepair, conn));
        }
    };
    for t in &tables {
        let tbl = match t.get::<String>(0) {
            Ok(tbl) => tbl,
            // sqlite_master.name is always TEXT — a non-string here is an
            // engine anomaly; fail closed rather than silently dropping the
            // table from the copy and verification.
            Err(e) => {
                crate::boot::boot_diagnostic(format!(
                    "store '{name}' table name is not text ({e}) — rebuild aborted; \
                     left for operator review",
                ));
                return Ok((RepairOutcome::NoRepair, conn));
            }
        };
        match count_table_rows(&conn, &tbl).await {
            Ok(count) => counts.push((tbl, count)),
            Err(e) => {
                // The data cannot be read, so the rebuild cannot preserve it: the
                // store is refused (never replaced). An actionable condition is
                // the environment, not the store — the caller propagates it.
                let err = anyhow::anyhow!(e);
                return Err(if is_actionable_signal(&err) {
                    err
                } else {
                    err.context(format!("table '{tbl}' cannot be read"))
                });
            }
        }
    }

    // ── Build the fresh store at a sibling temp path ──
    let temp = std::path::PathBuf::from(format!(
        "{}{REBUILD_TEMP_MARKER}{}",
        db_path.display(),
        family_stamp()
    ));
    // Guard removes the temp family on every exit, including a turso panic
    // mid-copy (absorbed by open_store's catch_unwind).
    let _temp_guard = TempCleanup(&temp);
    let fresh = match Connection::open(&temp).await {
        Ok(f) => f,
        Err(e) if is_actionable_signal(&e) => return Err(e),
        Err(e) => {
            crate::boot::boot_diagnostic(format!(
                "store '{name}' rebuild store open failed: {e} — left for operator review",
            ));
            return Ok((RepairOutcome::NoRepair, conn));
        }
    };
    // Schema replay (old creation order) + data copy.
    let migrated = migrate_schema_and_data(&conn, &fresh, &counts).await;
    let outcome = match migrated {
        Ok(()) => match fresh.quick_check().await {
            Ok(()) => checkpoint_rebuilt_before_swap(&fresh, name, root).await,
            Err(e) => Err(classify_migrate(e)),
        },
        Err(f) => Err(f),
    };
    drop(fresh); // release the fds before the temp cleanup / family swap
    if let Err(failure) = outcome {
        return match failure {
            MigrateFailure::Actionable(e) => Err(e),
            // The aliasing persists: every boot re-runs this full rebuild
            // attempt (fresh-store open + DDL replay + data copy) before
            // falling back to NoRepair — the operator-facing signal to
            // intervene (e.g. restore from backup).
            MigrateFailure::Finding(msg) => {
                crate::boot::boot_diagnostic(format!(
                    "store '{name}' rebuild aborted: {msg} — original store preserved \
                     for operator review (no data changed)",
                ));
                Ok((RepairOutcome::NoRepair, conn))
            }
        };
    }

    // ── Swap: quarantine the original family (forensic, never deleted), move
    // the fresh family into place, reopen with the module schema. ──
    drop(conn); // release the fds before the family rename
    if !quarantine_store_artifacts(db_path) {
        // A clobbering swap would destroy part of the original family
        // without a forensic record — never swap onto a partial quarantine.
        // The temp guard cleans the migrated family. The main renames
        // first; sibling renames normally fail together, so main-in-place
        // means the original main is preserved (reopening it reads the main
        // file plus its `-wal`) and main-moved means the data is not at its
        // path.
        crate::boot::boot_diagnostic(format!(
            "store '{name}' original family could not be fully quarantined — the \
             rebuild swap would clobber it without a forensic record; rebuild aborted, \
             migrated data discarded",
        ));
        return if db_path.exists() {
            crate::boot::boot_diagnostic(format!(
                "store '{name}' original family remains in place — left for operator \
                 review",
            ));
            open_with_schema(db_path, schema)
                .await
                .map(|reopened| (RepairOutcome::NoRepair, reopened))
        } else {
            crate::boot::boot_diagnostic(format!(
                "store '{name}' original family is in the quarantine and the store \
                 path is empty — boot aborted; recover from the quarantine and retry",
            ));
            Err(anyhow::anyhow!(
                "the rebuild aborted with the original family partially quarantined and the \
                 main file already moved — the store path was not rebuilt"
            ))
        };
    }
    // Main-file rename first; the `-wal` moves only when it succeeds. The fresh
    // store is normally TRUNCATE-checkpointed first (see
    // `checkpoint_rebuilt_before_swap`), so its main file alone holds every row;
    // when the pre-shrink gate refused that checkpoint the journal still holds
    // committed frames, and these two renames are the crash window that refusal
    // accepts.
    let wal = wal_path(db_path);
    let temp_wal = wal_path(&temp);
    if let Err(e) = std::fs::rename(&temp, db_path) {
        // The swap cannot proceed: the store path is absent and the original
        // family is in the quarantine. Bail loudly (the store's boot fails)
        // instead of opening a fresh empty store over the abandoned migrated
        // data; the temp guard discards the migrated family.
        return Err(anyhow::anyhow!(e).context(
            "the rebuild swap could not move the rebuilt store into place — migrated temp \
             family discarded; original family quarantined for recovery",
        ));
    }
    if temp_wal.exists()
        && let Err(e) = std::fs::rename(&temp_wal, &wal)
    {
        warn!(
            error = %e,
            from = %temp_wal.display(),
            to = %wal.display(),
            "rebuild swap sidecar rename failed",
        );
    }
    let reopened = match open_with_schema(db_path, schema).await {
        Ok(reopened) => reopened,
        Err(e) if is_actionable_signal(&e) => return Err(e),
        Err(e) => {
            // The reopened store failed — the quarantine holds the original.
            crate::boot::boot_diagnostic(format!(
                "store '{name}' rebuilt store reopen failed: {e} — original family is \
                 quarantined for recovery",
            ));
            return Err(e);
        }
    };
    // Post-swap verification: a genuine finding (integrity message or count
    // mismatch) reports loudly with its own diagnostic; a transient read
    // error on the healthy swapped store stays at warn level — "lost data"
    // must not fire on the latter (it could prompt restoring the corrupt
    // original over a healthy rebuild).
    let mut verified = true;
    let mut finding_reported = false;
    match reopened.quick_check().await {
        Ok(()) => {}
        Err(e) if is_actionable_signal(&e) => {
            warn!(error = %e, db = %name, "post-swap verification quick_check hit an actionable signal");
            verified = false;
        }
        Err(e) => {
            crate::boot::boot_diagnostic(format!(
                "store '{name}' rebuilt store failed post-swap quick_check ({e}) — \
                 original family is quarantined for recovery",
            ));
            verified = false;
            finding_reported = true;
        }
    }
    for (tbl, expected) in &counts {
        match count_table_rows(&reopened, tbl).await {
            // A read error is not proof of data loss — actionable signals
            // warn transiently, anything else is a genuine finding (the
            // "lost data" diagnostic must not fire on a read failure).
            Err(e) => {
                let err = anyhow::anyhow!(e);
                if is_actionable_signal(&err) {
                    verified = false;
                    warn!(
                        error = %err,
                        db = %name,
                        table = %tbl,
                        "post-swap counts verification query hit an actionable signal",
                    );
                } else {
                    crate::boot::boot_diagnostic(format!(
                        "store '{name}' post-swap verification counts query for table \
                         '{tbl}' failed ({err}) — verification incomplete; original \
                         family is quarantined for recovery",
                    ));
                    verified = false;
                    finding_reported = true;
                }
            }
            Ok(c) if c != *expected => {
                crate::boot::boot_diagnostic(format!(
                    "store '{name}' post-swap verification failed for table '{tbl}' \
                     (expected {expected} rows, found {c}) — the swap lost data; \
                     original family is quarantined for recovery",
                ));
                verified = false;
                finding_reported = true;
            }
            Ok(_) => {}
        }
    }
    if verified {
        info!(db = %name, "overflow-aliasing repaired: store rebuilt data-preservingly");
        Ok((RepairOutcome::Migrated, reopened))
    } else {
        // Transient read errors only (no finding reported above): the swap
        // succeeded and the store is in place — the next boot re-verifies.
        if !finding_reported {
            warn!(db = %name, "post-swap verification incomplete (transient read errors) — store is in place; re-verified on the next boot");
        }
        Ok((RepairOutcome::NoRepair, reopened))
    }
}

/// Fold the rebuilt store's WAL into the temp main file before the swap, so
/// a crash between the main and `-wal` renames cannot leave a valid-but-empty
/// store (turso does not checkpoint on close). The checkpoint is reclaiming, so
/// it passes the pre-shrink gate first; a refused gate simply skips the
/// checkpoint and the swap proceeds without the fold-in, leaving those two
/// renames as the crash window — the gate owns what a refusal means and where it
/// is recorded (see [`crate::db::shrink_gate`]).
///
/// The gate checks the rebuilt TEMP file (`conn`), not the live store's file.
async fn checkpoint_rebuilt_before_swap(
    conn: &Connection,
    name: &'static str,
    root: &Path,
) -> Result<(), MigrateFailure> {
    if !crate::db::shrink_gate::shrink_allowed(conn, name, Some(root)).await {
        return Ok(());
    }
    match conn.checkpoint_ungated().await {
        Ok(o) if o.is_complete() => Ok(()),
        Ok(o) => Err(MigrateFailure::Finding(format!(
            "rebuilt store checkpoint incomplete (busy={}, {} of {} frames)",
            o.busy, o.checkpointed_frames, o.log_frames,
        ))),
        Err(e) => Err(classify_migrate(e)),
    }
}

/// Failures of the overflow-aliasing rebuild, classified for the caller.
enum MigrateFailure {
    /// Actionable signal (resource/permission or lock contention) — propagate.
    Actionable(anyhow::Error),
    /// Data-integrity finding (constraint violation) or any other
    /// non-actionable failure — report only; the original store is preserved.
    Finding(String),
}

/// Classify a rebuild-path error: actionable signals propagate,
/// everything else is a report-only finding (covers both `turso::Error` from
/// the wrapper's query/execute and `anyhow::Error` from checkpoint/quick_check).
fn classify_migrate<E: Into<anyhow::Error>>(e: E) -> MigrateFailure {
    let err = e.into();
    if is_actionable_signal(&err) {
        MigrateFailure::Actionable(err)
    } else {
        MigrateFailure::Finding(format!("{err:#}"))
    }
}

/// Build `INSERT INTO "…" VALUES (…)` for a row copy using positional
/// placeholders ([`sql_in_placeholders`]); `table_ref` is a bare identifier —
/// the helper adds the surrounding double quotes.
fn row_insert_sql(table_ref: &str, row: &Row) -> Result<(String, Vec<Value>), MigrateFailure> {
    let ncols = row.column_count();
    let mut vals = Vec::with_capacity(ncols);
    for c in 0..ncols {
        vals.push(row.get_value(c).map_err(classify_migrate)?);
    }
    Ok((
        format!(
            "INSERT INTO \"{table_ref}\" VALUES ({})",
            sql_in_placeholders(ncols)
        ),
        vals,
    ))
}

/// Replay the old store's schema (tables + indexes, creation order) into the
/// fresh store and copy every table's data row by row (two connections — the
/// SQL engine cannot reference the old store from the fresh one). Indexes are
/// created before the data copy and maintained incrementally by the inserts.
/// Counts are verified per table; a mismatch or a constraint violation is a
/// data-integrity finding, not corruption.
async fn migrate_schema_and_data(
    old: &Connection,
    fresh: &Connection,
    counts: &[(String, i64)],
) -> Result<(), MigrateFailure> {
    let ddl_rows = old
        .query(
            &format!(
                "SELECT sql FROM sqlite_master \
                 WHERE sql IS NOT NULL \
                   AND {USER_OBJECT_FILTER} \
                 ORDER BY rowid"
            ),
            (),
        )
        .await
        .map_err(classify_migrate)?;
    for row in &ddl_rows {
        // sqlite_master.sql is always TEXT — a non-string here is an engine
        // anomaly; fail closed rather than silently skipping the object
        // (mirrors the counts loop's fail-closed name handling).
        let ddl = row
            .get::<String>(0)
            .map_err(|e| MigrateFailure::Finding(format!("DDL replay row is not text ({e})")))?;
        fresh.execute(&ddl, ()).await.map_err(classify_migrate)?;
    }
    // sqlite_sequence (AUTOINCREMENT bookkeeping) is auto-created by the
    // replayed DDLs; copy its rows so the old watermark survives the
    // explicit-id copy (WAL-mode explicit-rowid inserts advance, never
    // clobber) — deleted high ids must not be re-issued after migration
    // (surviving-rows tables; a fully-purged table restarts at 1, harmless).
    let has_sequence: i64 = old
        .query_row(
            "SELECT COUNT(*) FROM sqlite_master WHERE type='table' AND name='sqlite_sequence'",
            (),
            |r| r.get::<i64>(0),
        )
        .await
        .map_err(classify_migrate)?;
    if has_sequence > 0 {
        let seq_rows = old
            .query("SELECT * FROM sqlite_sequence", ())
            .await
            .map_err(classify_migrate)?;
        for row in &seq_rows {
            let (sql, vals) = row_insert_sql("sqlite_sequence", row)?;
            fresh.execute(&sql, vals).await.map_err(classify_migrate)?;
        }
    }
    for (tbl, expected) in counts {
        let quoted = tbl.replace('"', "\"\"");
        // Full-table materialization: `SELECT *` collects every row before
        // the copy loop — a boot-time memory spike on large stores (the
        // 324 MB-class sessions store), accepted for this rare repair path.
        let rows = old
            .query(&format!("SELECT * FROM \"{quoted}\""), ())
            .await
            .map_err(classify_migrate)?;
        let tx = fresh.begin_tx().await.map_err(classify_migrate)?;
        let mut copied = 0i64;
        for row in &rows {
            let (sql, vals) = row_insert_sql(&quoted, row)?;
            tx.execute(&sql, vals).await.map_err(classify_migrate)?;
            copied += 1;
        }
        tx.commit().await.map_err(classify_migrate)?;
        if copied != *expected {
            return Err(MigrateFailure::Finding(format!(
                "table '{tbl}' copy count {copied} != pre-migration {expected}",
            )));
        }
    }
    Ok(())
}

/// DROP+CREATE fallback for a REINDEX that could not clear the desync:
/// reproduce the index's original DDL from `sqlite_master` (validated on the
/// prod copy; clears desyncs REINDEX cannot).
async fn drop_create_index_fallback(
    conn: &Connection,
    name: &str,
    index: &str,
    quoted: &str,
) -> RepairOutcome {
    let ddl = conn
        .query_optional(
            "SELECT sql FROM sqlite_master WHERE type = 'index' AND name = ?",
            (index.to_string(),),
            |row| row.get::<String>(0),
        )
        .await
        .ok()
        .flatten();
    let Some(ddl) = ddl else {
        crate::boot::boot_diagnostic(format!(
            "store '{name}' index '{index}' DDL not found in sqlite_master — cannot \
             DROP+CREATE; left for operator review",
        ));
        return RepairOutcome::NoRepair;
    };
    // Transactional: `execute_batch` runs statements in autocommit, so a
    // failed rebuild (e.g. a UNIQUE-constraint violation on table data)
    // would leave the index permanently dropped. DROP+CREATE inside a tx
    // rolls the DROP back when the CREATE fails — the original (desynced)
    // index survives for operator review. The rollback is deferred: the
    // dropped guard flags the connection and the ROLLBACK fires at the next
    // detached access (`run_detached` / `lock_and_cleanup_owned`), so the
    // uncommitted DROP is undone before any further DB access.
    let outcome = async {
        let tx = conn.begin_tx().await?;
        tx.execute_batch(&format!("DROP INDEX \"{quoted}\"; {ddl};"))
            .await?;
        tx.commit().await
    }
    .await;
    match outcome {
        Ok(()) if conn.quick_check().await.is_ok() => {
            info!(
                db = %name,
                index = %index,
                "class-B btree index desync repaired in place (DROP+CREATE)",
            );
            RepairOutcome::Repaired
        }
        Ok(()) => {
            // The batch committed but the post-rebuild quick_check is not
            // clean (desync report or the scan itself failed to run) —
            // reported only; the store opens normally either way.
            crate::boot::boot_diagnostic(format!(
                "store '{name}' DROP+CREATE of '{index}' post-rebuild quick_check \
                 not clean — left for operator review",
            ));
            RepairOutcome::NoRepair
        }
        Err(repair_err) => {
            // The DROP is rolled back on the next connection operation
            // (deferred) — the original index is preserved, not dropped.
            crate::boot::boot_diagnostic(format!(
                "store '{name}' DROP+CREATE of '{index}' failed: {repair_err} — DROP \
                 rolled back on the next connection op, original index preserved; left \
                 for operator review",
            ));
            RepairOutcome::NoRepair
        }
    }
}

/// Extract the specific btree index name from a quick_check desync message
/// (`wrong # of entries in index <name>`). Returns `None` for any other
/// message shape (overflow-aliasing, unreadable table — the FTS false
/// positive is already filtered by [`scan_integrity_rows`] before quick_check
/// surfaces an error).
fn desynced_index_name(msg: &str) -> Option<&str> {
    const PREFIX: &str = "wrong # of entries in index ";
    let rest = msg.strip_prefix(PREFIX)?;
    let end = rest.find(['\n', ';', '\r']).unwrap_or(rest.len());
    let name = &rest[..end];
    (!name.is_empty()).then_some(name)
}


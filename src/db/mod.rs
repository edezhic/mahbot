/// The single shared consolidated domain connection, set once by
/// [`init_all_stores`]. Each domain store struct holds a clone of this
/// connection — literally one handle, whose writing connection is the one
/// transaction domain every domain write runs in and whose reader connections
/// serve the domain reads. The logs store does NOT use this connection.
pub(crate) static DOMAIN_CONN: tokio::sync::OnceCell<Connection> =
    tokio::sync::OnceCell::const_new();

/// Return an iterator over all **physical, checkpointable** database stores.
///
/// Each item is `(name, Option<&'static Connection>)` where `None` means the
/// store has not been initialized yet.
///
/// This is the single source of truth for which **physical files** exist and
/// are checkpointed. After consolidation all the domain stores share ONE file
/// ([`CONSOLIDATED_DB_NAME`]) plus the separate logs file, so this yields
/// exactly two units. [`store_names`] returns the LOGICAL store names accepted
/// by `mahbot debug --db <name>` — a deliberately separate list, because
/// several logical names map to the same physical file.
pub(crate) fn iter_checkpoint_stores()
-> impl Iterator<Item = (&'static str, Option<&'static crate::db::Connection>)> {
    [
        (CONSOLIDATED_DB_NAME, DOMAIN_CONN.get()),
        (LOG_DB_NAME, crate::logs::LOG_STORE.get().map(|s| &s.conn)),
    ]
    .into_iter()
}

/// Return all canonical **logical** store names accepted by `mahbot debug --db`.
///
/// These are the names users address stores by (`board`, `sessions`, …,
/// `chat_history`) plus `logs`. Several map to the single consolidated file via
/// [`store_db_path`]. This is **not** derived from
/// [`iter_checkpoint_stores`] (which enumerates the *physical* files): the two
/// lists are intentionally separate — several logical names share one physical
/// file. They change for different reasons: adding a consolidated domain
/// store only extends [`DOMAIN_STORE_NAMES`], from which this function
/// derives; [`iter_checkpoint_stores`] changes only when a brand-new physical
/// file appears. The name→file coupling itself lives in [`store_db_path`].
///
/// Used by:
/// - `mahbot debug` — validates `--db` argument values.
///
/// # Consolidated layout
///
/// The domain stores (board, sessions, workspaces, users, config, chat_history,
/// alarms, custom_roles, telegram_intake) are consolidated into ONE physical
/// file ([`CONSOLIDATED_DB_NAME`]); only the logs store is a separate file.
/// This function returns the LOGICAL store names so `--db board`, `--db sessions`,
/// etc. resolve to the single consolidated file via [`store_db_path`].
pub(crate) fn store_names() -> Vec<&'static str> {
    let mut names: Vec<&'static str> = DOMAIN_STORE_NAMES.to_vec();
    names.push(LOG_DB_NAME);
    names
}

/// All accepted database selector values for the read-only debug/query surface
/// (the CLI's `--db` argument and the Assistant `mahbot_debug` tool's `db`
/// parameter): the logical store names ([`store_names`]) plus the physical
/// consolidated file name ([`CONSOLIDATED_DB_NAME`]).
///
/// This is the single derivation of that accepted set — [`crate::db::debug`]'s
/// validator, CLI usage text, and the tool's model-facing schema all use it so
/// the three cannot drift.
pub(crate) fn debug_db_names() -> Vec<&'static str> {
    let mut names = store_names();
    names.push(CONSOLIDATED_DB_NAME);
    names
}

/// Initialize all database stores concurrently.
///
/// This is the canonical initialization path for the domain stores (board,
/// session, workspace, users, chat_history, config, alarms, custom_roles,
/// telegram_intake).
/// The `logs` store
/// is **not** included here because it must be initialized earlier via
/// [`crate::logs::init_tracing`], which requires the log store before any
/// other subsystem is ready. The stats tables (tool_calls, llm_requests)
/// live in the logs store.
///
/// # Consolidated layout
///
/// The domain stores (`DOMAIN_STORE_NAMES`) now share ONE file
/// ([`CONSOLIDATED_DB_NAME`]) and ONE shared [`Connection`] ([`DOMAIN_CONN`]) —
/// every store struct holds a clone of the same connection, so `begin_tx` on
/// any store acquires the same mutex and phase+stage updates are atomic within
/// a single transaction domain. The
/// consolidated schema + migrations are applied once via
/// [`open_consolidated_store`], and per-store post-open hooks (tickets FTS
/// index, admin-user seed) run idempotently before the cells are set.
pub async fn init_all_stores() -> anyhow::Result<()> {
    // Idempotent: the consolidated connection is set once. Re-entering (e.g.
    // a test that calls init_test_stores twice) must not re-open / re-migrate.
    if DOMAIN_CONN.get().is_some() {
        return Ok(());
    }

    let root = crate::config::CONFIG.global_storage_root();
    let conn = open_consolidated_store(&root).await?;

    // Run the idempotent per-store post-open hooks on the shared connection,
    // in a defined order, before exposing the store cells.
    let board = crate::pipeline::board::BoardStore { conn: conn.clone() };
    board.after_open(&root).await?;
    let users = crate::users::UserStore { conn: conn.clone() };
    users.ensure_admin_user().await?;

    let session = crate::session::SessionStore { conn: conn.clone() };
    let workspace = crate::workspace::WorkspaceStore { conn: conn.clone() };
    let config = crate::config_db::ConfigStore { conn: conn.clone() };
    let chat_history = crate::channels::chat_history::ChatHistoryStore { conn: conn.clone() };
    let telegram_intake =
        crate::channels::telegram_intake::TelegramIntakeStore { conn: conn.clone() };
    let alarms = crate::alarms::AlarmStore { conn: conn.clone() };
    let custom_roles = crate::custom_role::CustomRoleStore { conn: conn.clone() };

    // Record the shared connection before setting any cell so a concurrent
    // re-entry observes it and short-circuits.
    let _ = DOMAIN_CONN.set(conn.clone());

    // Start the CDC drain loop once. It broadcasts ticket change events to the
    // GUI and the chronicle subscriber; a reopen (the data-preserving rebuild)
    // re-enables capture in open_consolidated_store (above).
    crate::db::cdc::spawn_drainer(conn.clone());

    init_cell(&crate::pipeline::board::BOARD, board, "BOARD")?;
    init_cell(&crate::session::SESSIONS, session, "SESSIONS")?;
    init_cell(&crate::workspace::WORKSPACES, workspace, "WORKSPACES")?;
    init_cell(&crate::users::USER_STORE, users, "USER_STORE")?;
    init_cell(&crate::config_db::CONFIG_STORE, config, "CONFIG_STORE")?;
    init_cell(
        &crate::channels::chat_history::CHAT_HISTORY,
        chat_history,
        "CHAT_HISTORY",
    )?;
    init_cell(
        &crate::channels::telegram_intake::TELEGRAM_INTAKE,
        telegram_intake,
        "TELEGRAM_INTAKE",
    )?;
    init_cell(&crate::alarms::ALARMS, alarms, "ALARMS")?;
    init_cell(
        &crate::custom_role::CUSTOM_ROLES,
        custom_roles,
        "CUSTOM_ROLES",
    )?;

    Ok(())
}

/// Set a store's global cell exactly once, failing with the store's canonical
/// "already initialized" error otherwise (`name` is the cell's literal name).
fn init_cell<T>(cell: &tokio::sync::OnceCell<T>, value: T, name: &str) -> anyhow::Result<()> {
    cell.set(value)
        .map_err(|_| anyhow::anyhow!("{name} already initialized"))
}

